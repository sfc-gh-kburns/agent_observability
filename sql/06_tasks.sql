-- =====================================================================
-- 06_tasks.sql — orchestration
-- One task graph so each cycle resumes the warehouse once:
--   T_AGENT_OBS_ROOT (schedule)                  events + usage + CoCo/AI-function usage + query history
--     └─ T_AGENT_OBS_CONFIG   (hourly-gated)     agent config SCD2
--     └─ T_AGENT_OBS_DAILY    (daily-gated)      assets + users
--          (finalizer) T_AGENT_OBS_REFRESH       refresh MART DTs (cascades through CORE), then question trends
-- All DTs use TARGET_LAG = DOWNSTREAM, so nothing refreshes on its own.
-- Cadence is ADMIN.CONFIG 'PIPELINE_SCHEDULE' (applied by SP_SET_SCHEDULE).
-- =====================================================================
USE ROLE AGENT_OBS_INGEST_ROLE;
USE WAREHOUSE AGENT_OBS_WH;
USE SCHEMA AGENT_OBS.ADMIN;

MERGE INTO ADMIN.CONFIG t USING (SELECT * FROM VALUES
  ('PIPELINE_SCHEDULE', 'USING CRON 0 * * * * UTC', 'Root task schedule (hourly default; 15-min = USING CRON */15 * * * * UTC)')
  AS s(KEY, VALUE, DESCRIPTION)) s ON t.KEY = s.KEY
WHEN NOT MATCHED THEN INSERT (KEY, VALUE, DESCRIPTION) VALUES (s.KEY, s.VALUE, s.DESCRIPTION);

-- Gating helpers (a step runs if its last OK run is older than its interval)
CREATE OR REPLACE PROCEDURE ADMIN.SP_RUN_IF_DUE(STEP STRING, PROC STRING, MIN_MINUTES NUMBER)
RETURNS VARIANT LANGUAGE SQL EXECUTE AS CALLER AS
$$
DECLARE last_ok TIMESTAMP_LTZ; res VARIANT;
BEGIN
  SELECT MAX(STARTED_AT) INTO :last_ok FROM AGENT_OBS.ADMIN.LOAD_LOG WHERE STEP = :STEP AND STATUS IN ('OK','PARTIAL');
  IF (last_ok IS NOT NULL AND DATEDIFF(minute, last_ok, CURRENT_TIMESTAMP()) < MIN_MINUTES) THEN
    RETURN OBJECT_CONSTRUCT('step', STEP, 'skipped', TRUE);
  END IF;
  EXECUTE IMMEDIATE 'CALL AGENT_OBS.ADMIN.' || PROC || '()';
  SELECT $1 INTO :res FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));
  RETURN res;
END;
$$;

CREATE OR REPLACE PROCEDURE ADMIN.SP_REFRESH_MART(FORCE BOOLEAN DEFAULT FALSE)
RETURNS VARIANT LANGUAGE SQL EXECUTE AS CALLER AS
$$
DECLARE
  run_id STRING DEFAULT UUID_STRING();
  started TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP();
  changed NUMBER DEFAULT 0;
  last_refresh TIMESTAMP_LTZ;
BEGIN
  -- Skip when no load changed rows since the last successful refresh (keeps idle cycles cheap).
  SELECT MAX(STARTED_AT) INTO :last_refresh FROM AGENT_OBS.ADMIN.LOAD_LOG WHERE STEP = 'REFRESH_MART' AND STATUS = 'OK';
  SELECT COALESCE(SUM(COALESCE(ROWS_INSERTED,0) + COALESCE(ROWS_UPDATED,0)), 0) INTO :changed
  FROM AGENT_OBS.ADMIN.LOAD_LOG
  WHERE STEP <> 'REFRESH_MART' AND STATUS IN ('OK','PARTIAL')
    AND STARTED_AT > COALESCE(:last_refresh, '1970-01-01'::TIMESTAMP_LTZ);
  IF (NOT FORCE AND changed = 0 AND last_refresh IS NOT NULL) THEN
    RETURN OBJECT_CONSTRUCT('step','REFRESH_MART','skipped',TRUE);
  END IF;
  -- Refreshing the leaves pulls every upstream DOWNSTREAM-lag DT (CORE) to the same data timestamp.
  ALTER DYNAMIC TABLE AGENT_OBS.MART.AGG_AGENT_DAILY    REFRESH;
  ALTER DYNAMIC TABLE AGENT_OBS.MART.AGG_FEEDBACK_DAILY REFRESH;
  ALTER DYNAMIC TABLE AGENT_OBS.MART.AGG_MODEL_DAILY    REFRESH;
  ALTER DYNAMIC TABLE AGENT_OBS.MART.AGG_TOOL_DAILY     REFRESH;
  ALTER DYNAMIC TABLE AGENT_OBS.MART.AGG_PLANNING_DEPTH REFRESH;
  ALTER DYNAMIC TABLE AGENT_OBS.MART.AGG_ASSET_DAILY    REFRESH;
  -- CORE tables read only by MART views (not by an AGG_*) need their own refresh.
  ALTER DYNAMIC TABLE AGENT_OBS.CORE.FACT_SQL_EXECUTION REFRESH;
  ALTER DYNAMIC TABLE AGENT_OBS.CORE.FACT_SEARCH_CALL   REFRESH;
  ALTER DYNAMIC TABLE AGENT_OBS.CORE.FACT_THREAD        REFRESH;
  CALL AGENT_OBS.ADMIN.SP_LOG(:run_id, 'REFRESH_MART', :started, :changed, 0, NULL, 'OK', NULL);
  RETURN OBJECT_CONSTRUCT('step','REFRESH_MART','source_rows_changed',changed);
EXCEPTION WHEN OTHER THEN
  CALL AGENT_OBS.ADMIN.SP_LOG(:run_id, 'REFRESH_MART', :started, 0, 0, NULL, 'FAILED', :SQLERRM);
  RAISE;
END;
$$;

-- Task graph ---------------------------------------------------------------
CREATE OR REPLACE TASK ADMIN.T_AGENT_OBS_ROOT
  USER_TASK_MANAGED_INITIAL_WAREHOUSE_SIZE = 'XSMALL'   -- serverless: billed per second, no warehouse minimum
  SCHEDULE = 'USING CRON 0 * * * * UTC'
  SUSPEND_TASK_AFTER_NUM_FAILURES = 5
  ALLOW_OVERLAPPING_EXECUTION = FALSE
  COMMENT = 'AGENT_OBS: load events, usage, CoCo + AI function usage, automations, agent query history'
AS
EXECUTE IMMEDIATE $$
BEGIN
  CALL AGENT_OBS.ADMIN.SP_LOAD_EVENTS();
  CALL AGENT_OBS.ADMIN.SP_LOAD_USAGE();
  CALL AGENT_OBS.ADMIN.SP_LOAD_CODE_USAGE();
  CALL AGENT_OBS.ADMIN.SP_LOAD_AI_FUNCTION_USAGE();
  CALL AGENT_OBS.ADMIN.SP_LOAD_AUTOMATIONS();       -- defined in 09_automations.sql
  CALL AGENT_OBS.ADMIN.SP_LOAD_QUERY_HISTORY();
END;
$$;

CREATE OR REPLACE TASK ADMIN.T_AGENT_OBS_CONFIG
  USER_TASK_MANAGED_INITIAL_WAREHOUSE_SIZE = 'XSMALL'
  COMMENT = 'AGENT_OBS: agent config SCD2 snapshot (at most every 55 min)'
  AFTER ADMIN.T_AGENT_OBS_ROOT
AS
  CALL AGENT_OBS.ADMIN.SP_RUN_IF_DUE('AGENT_CONFIG', 'SP_LOAD_AGENT_CONFIG', 55);

CREATE OR REPLACE TASK ADMIN.T_AGENT_OBS_DAILY
  USER_TASK_MANAGED_INITIAL_WAREHOUSE_SIZE = 'XSMALL'
  COMMENT = 'AGENT_OBS: asset + user snapshots (once per day)'
  AFTER ADMIN.T_AGENT_OBS_ROOT
AS
EXECUTE IMMEDIATE $$
BEGIN
  CALL AGENT_OBS.ADMIN.SP_RUN_IF_DUE('ASSETS', 'SP_LOAD_ASSETS', 1380);
  CALL AGENT_OBS.ADMIN.SP_RUN_IF_DUE('USERS',  'SP_LOAD_USERS',  1380);
END;
$$;

CREATE OR REPLACE TASK ADMIN.T_AGENT_OBS_REFRESH
  USER_TASK_MANAGED_INITIAL_WAREHOUSE_SIZE = 'XSMALL'   -- DT refreshes themselves run on AGENT_OBS_WH
  COMMENT = 'AGENT_OBS: refresh CORE/MART dynamic tables after loads, then classify new questions'
  FINALIZE = ADMIN.T_AGENT_OBS_ROOT
AS
EXECUTE IMMEDIATE $$
BEGIN
  CALL AGENT_OBS.ADMIN.SP_REFRESH_MART();
  CALL AGENT_OBS.ADMIN.SP_REFRESH_TRENDS();   -- defined in 08_trends.sql
END;
$$;

-- Apply cadence from config + (re)start the graph
CREATE OR REPLACE PROCEDURE ADMIN.SP_SET_SCHEDULE(START_PIPELINE BOOLEAN)
RETURNS STRING LANGUAGE SQL EXECUTE AS CALLER AS
$$
DECLARE sched STRING;
BEGIN
  sched := (SELECT AGENT_OBS.ADMIN.CFG('PIPELINE_SCHEDULE'));
  ALTER TASK AGENT_OBS.ADMIN.T_AGENT_OBS_ROOT SUSPEND;
  EXECUTE IMMEDIATE 'ALTER TASK AGENT_OBS.ADMIN.T_AGENT_OBS_ROOT SET SCHEDULE = ''' || REPLACE(sched, '''', '') || '''';
  IF (START_PIPELINE) THEN
    SELECT SYSTEM$TASK_DEPENDENTS_ENABLE('AGENT_OBS.ADMIN.T_AGENT_OBS_ROOT');
    RETURN 'pipeline started: ' || sched;
  END IF;
  RETURN 'schedule set (suspended): ' || sched;
END;
$$;
