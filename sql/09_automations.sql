-- =====================================================================
-- 09_automations.sql — scheduled automations created by users
--   CoWork automations : tasks in USER$<user>.SNOWFLAKE_INTELLIGENCE that call
--                        SYSTEM$CORTEX_DATA_AGENT_RUN_V2('<agent>', '<request json>')
--   CoCo automations   : agent tasks in USER$<user>.PUBLIC named COCO_ROUTINE_*
--   Agent SDK          : other agent-run tasks in USER$<user>.PUBLIC
-- RAW keeps every definition (incl. deleted tasks), every run and task
-- compute, because ACCOUNT_USAGE ages out and automation threads are kept
-- only two months. Prompts and definitions are content (masked).
-- =====================================================================
USE ROLE AGENT_OBS_INGEST_ROLE;
USE WAREHOUSE AGENT_OBS_WH;
USE DATABASE AGENT_OBS;

-- RAW.AUTOMATION_TASK / AUTOMATION_RUN / AUTOMATION_TASK_CREDITS are created in 01_raw.sql.

-- Which personal-database tasks count as automations, and of what kind.
CREATE OR REPLACE FUNCTION ADMIN.AUTOMATION_KIND(DB STRING, SCH STRING, NAME STRING, DEF STRING) RETURNS STRING AS
$$
  CASE WHEN DB NOT ILIKE 'USER$%' THEN NULL
       WHEN UPPER(SCH) = 'SNOWFLAKE_INTELLIGENCE' THEN 'COWORK'
       WHEN UPPER(SCH) = 'PUBLIC' AND UPPER(NAME) LIKE 'COCO\\_ROUTINE\\_%' ESCAPE '\\' THEN 'COCO'
       WHEN UPPER(SCH) = 'PUBLIC' AND DEF ILIKE '%CORTEX_DATA_AGENT_RUN%' THEN 'AGENT_SDK'
       ELSE 'OTHER' END
$$;

-- 1. Task definitions (MERGE on task id; deleted tasks are kept with DELETED set)
CREATE OR REPLACE PROCEDURE ADMIN.SP_LOAD_AUTOMATIONS()
RETURNS VARIANT LANGUAGE SQL EXECUTE AS CALLER AS
$$
DECLARE
  run_id STRING DEFAULT UUID_STRING();
  started TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP();
  wm TIMESTAMP_LTZ;
  ins NUMBER DEFAULT 0; upd NUMBER DEFAULT 0; runs NUMBER DEFAULT 0; cr NUMBER DEFAULT 0;
BEGIN
  MERGE INTO AGENT_OBS.RAW.AUTOMATION_TASK t USING (
    WITH src AS (
      SELECT k.ID::STRING AS TASK_ID,
             AGENT_OBS.ADMIN.AUTOMATION_KIND(k.TASK_DATABASE, k.TASK_SCHEMA, k.TASK_NAME, k.DEFINITION) AS KIND,
             k.TASK_DATABASE, k.TASK_SCHEMA, k.TASK_NAME, REGEXP_REPLACE(k.TASK_DATABASE, '^USER\\$', '', 1, 1, 'i') AS OWNER_USER,
             k.TASK_OWNER, k.COMMENT AS TITLE, k.STATE, k.SCHEDULE,
             COALESCE(REGEXP_SUBSTR(k.SCHEDULE, 'CRON\\s+\\S+\\s+\\S+\\s+\\S+\\s+\\S+\\s+\\S+\\s+(\\S+)', 1, 1, 'i', 1), 'UTC') AS TIMEZONE,
             REGEXP_SUBSTR(k.DEFINITION, 'CORTEX_DATA_AGENT_RUN(_V2)?\\(\\s*''([^'']+)''', 1, 1, 'ie', 2) AS TARGET_AGENT,
             TRY_PARSE_JSON(REPLACE(REGEXP_SUBSTR(k.DEFINITION, 'CORTEX_DATA_AGENT_RUN(_V2)?\\(\\s*''[^'']+''\\s*,\\s*''(\\{.*\\})''', 1, 1, 'is', 2), '''''', '''')) AS REQ,
             k.DEFINITION, k.CREATED, k.LAST_ALTERED, k.DELETED, k.LAST_SUSPENDED, k.LAST_SUSPENDED_REASON,
             k.CREATED_BY_USER_ID, k.EXECUTE_AS_USER_ID, TRY_PARSE_JSON(k.CONFIG) AS CONFIG
      FROM SNOWFLAKE.ACCOUNT_USAGE.TASKS k
      WHERE k.TASK_DATABASE ILIKE 'USER$%'
      QUALIFY ROW_NUMBER() OVER (PARTITION BY k.ID ORDER BY k.LAST_ALTERED DESC NULLS LAST, k.DELETED DESC NULLS FIRST) = 1
    )
    SELECT TASK_ID, KIND, TASK_DATABASE, TASK_SCHEMA, TASK_NAME, OWNER_USER, TASK_OWNER, TITLE, STATE, SCHEDULE, TIMEZONE,
           TARGET_AGENT, COALESCE(REQ:messages[ARRAY_SIZE(REQ:messages) - 1]:content[0]:text::STRING, REQ:prompt::STRING) AS PROMPT,
           DEFINITION, CREATED, LAST_ALTERED, DELETED, LAST_SUSPENDED, LAST_SUSPENDED_REASON,
           CREATED_BY_USER_ID, EXECUTE_AS_USER_ID, CONFIG,
           HASH(STATE, SCHEDULE, TITLE, DEFINITION, LAST_ALTERED, DELETED, LAST_SUSPENDED, LAST_SUSPENDED_REASON, CONFIG) AS ROW_HASH
    FROM src
  ) s ON t.TASK_ID = s.TASK_ID
  WHEN MATCHED AND t.ROW_HASH <> s.ROW_HASH THEN UPDATE SET
    KIND = s.KIND, TASK_DATABASE = s.TASK_DATABASE, TASK_SCHEMA = s.TASK_SCHEMA, TASK_NAME = s.TASK_NAME,
    OWNER_USER = s.OWNER_USER, TASK_OWNER = s.TASK_OWNER, TITLE = s.TITLE, STATE = s.STATE, SCHEDULE = s.SCHEDULE,
    TIMEZONE = s.TIMEZONE, TARGET_AGENT = s.TARGET_AGENT, PROMPT = s.PROMPT, DEFINITION = s.DEFINITION,
    CREATED = s.CREATED, LAST_ALTERED = s.LAST_ALTERED, DELETED = s.DELETED, LAST_SUSPENDED = s.LAST_SUSPENDED,
    LAST_SUSPENDED_REASON = s.LAST_SUSPENDED_REASON, CREATED_BY_USER_ID = s.CREATED_BY_USER_ID,
    EXECUTE_AS_USER_ID = s.EXECUTE_AS_USER_ID, CONFIG = s.CONFIG, ROW_HASH = s.ROW_HASH, _LAST_LOADED_AT = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN INSERT VALUES (
    s.TASK_ID, s.KIND, s.TASK_DATABASE, s.TASK_SCHEMA, s.TASK_NAME, s.OWNER_USER, s.TASK_OWNER, s.TITLE, s.STATE, s.SCHEDULE,
    s.TIMEZONE, s.TARGET_AGENT, s.PROMPT, s.DEFINITION, s.CREATED, s.LAST_ALTERED, s.DELETED, s.LAST_SUSPENDED,
    s.LAST_SUSPENDED_REASON, s.CREATED_BY_USER_ID, s.EXECUTE_AS_USER_ID, s.CONFIG, s.ROW_HASH, CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP());
  SELECT "number of rows inserted", "number of rows updated" INTO :ins, :upd FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

  -- 2. Runs: re-read 2 days behind the newest run so late rows and state changes land.
  SELECT COALESCE(DATEADD(day, -2, MAX(SCHEDULED_TIME)), AGENT_OBS.ADMIN.CFG('BACKFILL_START')::TIMESTAMP_LTZ)
    INTO :wm FROM AGENT_OBS.RAW.AUTOMATION_RUN;
  MERGE INTO AGENT_OBS.RAW.AUTOMATION_RUN t USING (
    SELECT SHA2(h.DATABASE_NAME || '|' || h.SCHEMA_NAME || '|' || h.NAME || '|' || h.SCHEDULED_TIME::STRING || '|' || COALESCE(h.ATTEMPT_NUMBER, 1)) AS RUN_KEY,
           h.DATABASE_NAME, h.SCHEMA_NAME, h.NAME, h.SCHEDULED_TIME, h.QUERY_START_TIME, h.COMPLETED_TIME, h.STATE,
           h.ERROR_CODE, h.ERROR_MESSAGE, h.RETURN_VALUE, h.QUERY_ID, h.RUN_ID, h.ATTEMPT_NUMBER, h.SCHEDULED_FROM, h.SCHEDULED_BY_USER,
           HASH(h.STATE, h.COMPLETED_TIME, h.ERROR_CODE, h.ERROR_MESSAGE, h.QUERY_ID, h.RETURN_VALUE) AS ROW_HASH
    FROM SNOWFLAKE.ACCOUNT_USAGE.TASK_HISTORY h
    WHERE h.DATABASE_NAME ILIKE 'USER$%' AND h.SCHEDULED_TIME >= :wm
    QUALIFY ROW_NUMBER() OVER (PARTITION BY RUN_KEY ORDER BY h.COMPLETED_TIME DESC NULLS LAST) = 1
  ) s ON t.RUN_KEY = s.RUN_KEY
  WHEN MATCHED AND t.ROW_HASH <> s.ROW_HASH THEN UPDATE SET
    QUERY_START_TIME = s.QUERY_START_TIME, COMPLETED_TIME = s.COMPLETED_TIME, STATE = s.STATE, ERROR_CODE = s.ERROR_CODE,
    ERROR_MESSAGE = s.ERROR_MESSAGE, RETURN_VALUE = s.RETURN_VALUE, QUERY_ID = s.QUERY_ID, ROW_HASH = s.ROW_HASH,
    _LAST_LOADED_AT = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN INSERT VALUES (
    s.RUN_KEY, s.DATABASE_NAME, s.SCHEMA_NAME, s.NAME, s.SCHEDULED_TIME, s.QUERY_START_TIME, s.COMPLETED_TIME, s.STATE,
    s.ERROR_CODE, s.ERROR_MESSAGE, s.RETURN_VALUE, s.QUERY_ID, s.RUN_ID, s.ATTEMPT_NUMBER, s.SCHEDULED_FROM, s.SCHEDULED_BY_USER,
    s.ROW_HASH, CURRENT_TIMESTAMP());
  runs := SQLROWCOUNT;

  -- 3. Task compute (serverless), hourly rows; replace the re-read window.
  BEGIN TRANSACTION;
  DELETE FROM AGENT_OBS.RAW.AUTOMATION_TASK_CREDITS WHERE START_TIME >= :wm;
  INSERT INTO AGENT_OBS.RAW.AUTOMATION_TASK_CREDITS
  SELECT TASK_ID::STRING, DATABASE_NAME, SCHEMA_NAME, TASK_NAME, START_TIME, END_TIME, CREDITS_USED, CURRENT_TIMESTAMP()
  FROM SNOWFLAKE.ACCOUNT_USAGE.SERVERLESS_TASK_HISTORY
  WHERE DATABASE_NAME ILIKE 'USER$%' AND START_TIME >= :wm;
  cr := SQLROWCOUNT;
  COMMIT;

  CALL AGENT_OBS.ADMIN.SP_LOG(:run_id, 'AUTOMATIONS', :started, :ins + :runs + :cr, :upd, :wm, 'OK', NULL);
  RETURN OBJECT_CONSTRUCT('step','AUTOMATIONS','tasks_inserted',ins,'tasks_updated',upd,'runs',runs,'credit_rows',cr,'from',wm);
EXCEPTION WHEN OTHER THEN
  ROLLBACK;
  CALL AGENT_OBS.ADMIN.SP_LOG(:run_id, 'AUTOMATIONS', :started, 0, 0, :wm, 'FAILED', :SQLERRM);
  RAISE;
END;
$$;

-- Content masking on prompt text (idempotent)
EXECUTE IMMEDIATE $$
DECLARE
  c CURSOR FOR SELECT col FROM VALUES ('PROMPT'), ('DEFINITION') AS v(col);
BEGIN
  FOR r IN c DO
    BEGIN
      EXECUTE IMMEDIATE 'ALTER TABLE AGENT_OBS.RAW.AUTOMATION_TASK MODIFY COLUMN ' || r.col || ' UNSET MASKING POLICY';
    EXCEPTION WHEN OTHER THEN NULL;
    END;
    EXECUTE IMMEDIATE 'ALTER TABLE AGENT_OBS.RAW.AUTOMATION_TASK MODIFY COLUMN ' || r.col || ' SET MASKING POLICY AGENT_OBS.ADMIN.MP_CONTENT_STRING';
  END FOR;
  RETURN 'automation content columns protected';
END;
$$;

-- ---------------------------------------------------------------------
-- MART
-- ---------------------------------------------------------------------
-- One row per run. Agent / CoCo credits are attributed from the usage views:
-- rows with trigger_type = 'automation' for the same user (and agent, for
-- agent runs) that start inside the run window (plus a 2 minute margin).
CREATE OR REPLACE VIEW MART.V_AUTOMATION_RUN COMMENT = 'Automation runs with task compute and attributed agent / CoCo credits' AS
WITH r AS (
  SELECT r.*, a.TASK_ID, a.KIND, a.OWNER_USER, a.TITLE, a.TARGET_AGENT,
         COALESCE(r.QUERY_START_TIME, r.SCHEDULED_TIME) AS RUN_START,
         COALESCE(r.COMPLETED_TIME, DATEADD(hour, 1, COALESCE(r.QUERY_START_TIME, r.SCHEDULED_TIME))) AS RUN_END
  FROM AGENT_OBS.RAW.AUTOMATION_RUN r
  JOIN AGENT_OBS.RAW.AUTOMATION_TASK a
    ON a.TASK_DATABASE = r.TASK_DATABASE AND a.TASK_SCHEMA = r.TASK_SCHEMA AND a.TASK_NAME = r.TASK_NAME
  QUALIFY ROW_NUMBER() OVER (PARTITION BY r.RUN_KEY ORDER BY a.DELETED NULLS FIRST, a.CREATED DESC) = 1
), agent_cost AS (
  SELECT r.RUN_KEY, SUM(u.TOKEN_CREDITS + COALESCE(u.METADATA:ai_functions_credits::FLOAT, 0)
                        + COALESCE(u.METADATA:sql_query_credits::FLOAT, 0)) AS AGENT_CREDITS,
         COUNT(*) AS AGENT_TURNS, MAX(u.REQUEST_ID) AS REQUEST_ID, MAX(NULLIF(u.THREAD_ID, 0))::STRING AS THREAD_ID
  FROM r JOIN AGENT_OBS.RAW.USAGE_TURN u
    ON u.METADATA:trigger_type::STRING = 'automation' AND u.USER_NAME = r.OWNER_USER
   AND (r.TARGET_AGENT IS NULL OR UPPER(u.AGENT_DATABASE_NAME || '.' || u.AGENT_SCHEMA_NAME || '.' || u.AGENT_NAME) = UPPER(r.TARGET_AGENT))
   AND u.START_TIME BETWEEN DATEADD(minute, -2, r.RUN_START) AND DATEADD(minute, 2, r.RUN_END)
  GROUP BY 1
), coco_cost AS (
  SELECT r.RUN_KEY, SUM(c.TOKEN_CREDITS) AS CODE_CREDITS, COUNT(*) AS CODE_REQUESTS, MAX(NULLIF(c.THREAD_ID, 0))::STRING AS THREAD_ID
  FROM r JOIN AGENT_OBS.RAW.CODE_USAGE c
    ON c.METADATA:trigger_type::STRING = 'automation' AND c.USER_NAME = r.OWNER_USER
   AND c.USAGE_TIME BETWEEN DATEADD(minute, -2, r.RUN_START) AND DATEADD(minute, 2, r.RUN_END)
  WHERE r.KIND = 'COCO'
  GROUP BY 1
), task_cost AS (
  -- Serverless task credits are hourly, so a run gets its task's credits for the hour it started in.
  SELECT r.RUN_KEY, SUM(k.CREDITS_USED) / NULLIF(COUNT(DISTINCT r2.RUN_KEY), 0) AS TASK_CREDITS
  -- SERVERLESS_TASK_HISTORY.TASK_ID is a numeric id unlike TASKS.ID, so match on the task's name.
  FROM r JOIN AGENT_OBS.RAW.AUTOMATION_TASK_CREDITS k
    ON k.TASK_DATABASE = r.TASK_DATABASE AND k.TASK_SCHEMA = r.TASK_SCHEMA AND k.TASK_NAME = r.TASK_NAME
   AND DATE_TRUNC('hour', r.RUN_START) = DATE_TRUNC('hour', k.START_TIME)
  JOIN r r2 ON r2.TASK_ID = r.TASK_ID AND DATE_TRUNC('hour', r2.RUN_START) = DATE_TRUNC('hour', r.RUN_START)
  GROUP BY 1
)
SELECT r.RUN_KEY, r.TASK_ID, r.KIND, r.OWNER_USER, r.TASK_DATABASE, r.TASK_SCHEMA, r.TASK_NAME, r.TITLE, r.TARGET_AGENT,
       r.SCHEDULED_TIME, r.QUERY_START_TIME, r.COMPLETED_TIME, TO_DATE(r.SCHEDULED_TIME) AS DAY,
       DATEDIFF(millisecond, r.QUERY_START_TIME, r.COMPLETED_TIME) AS DURATION_MS,
       r.STATE, r.STATE = 'SUCCEEDED' AS IS_SUCCESS, r.STATE IN ('FAILED', 'FAILED_AND_AUTO_SUSPENDED') AS IS_FAILED,
       r.ERROR_CODE, r.ERROR_MESSAGE, r.RETURN_VALUE, r.QUERY_ID, r.SCHEDULED_FROM, r.ATTEMPT_NUMBER,
       tc.TASK_CREDITS, ac.AGENT_CREDITS, ac.AGENT_TURNS, cc.CODE_CREDITS, cc.CODE_REQUESTS,
       COALESCE(tc.TASK_CREDITS, 0) + COALESCE(ac.AGENT_CREDITS, 0) + COALESCE(cc.CODE_CREDITS, 0) AS TOTAL_CREDITS,
       COALESCE(ac.THREAD_ID, cc.THREAD_ID) AS THREAD_ID
FROM r
LEFT JOIN agent_cost ac ON ac.RUN_KEY = r.RUN_KEY
LEFT JOIN coco_cost  cc ON cc.RUN_KEY = r.RUN_KEY
LEFT JOIN task_cost  tc ON tc.RUN_KEY = r.RUN_KEY;

CREATE OR REPLACE VIEW MART.V_AUTOMATION COMMENT = 'One row per user automation (CoWork, CoCo, Agent SDK) with run health and cost' AS
WITH runs AS (
  SELECT TASK_ID,
         COUNT(*) AS RUNS, COUNT_IF(IS_SUCCESS) AS SUCCEEDED, COUNT_IF(IS_FAILED) AS FAILED,
         COUNT_IF(SCHEDULED_TIME > DATEADD(day, -30, CURRENT_TIMESTAMP())) AS RUNS_30D,
         COUNT_IF(IS_FAILED AND SCHEDULED_TIME > DATEADD(day, -30, CURRENT_TIMESTAMP())) AS FAILED_30D,
         MEDIAN(DURATION_MS) AS P50_MS, MAX(DURATION_MS) AS MAX_MS,
         SUM(TOTAL_CREDITS) AS TOTAL_CREDITS, SUM(TASK_CREDITS) AS TASK_CREDITS,
         SUM(AGENT_CREDITS) AS AGENT_CREDITS, SUM(CODE_CREDITS) AS CODE_CREDITS,
         SUM(IFF(SCHEDULED_TIME > DATEADD(day, -30, CURRENT_TIMESTAMP()), TOTAL_CREDITS, 0)) AS CREDITS_30D,
         MIN(SCHEDULED_TIME) AS FIRST_RUN, MAX(SCHEDULED_TIME) AS LAST_RUN,
         MAX_BY(STATE, SCHEDULED_TIME) AS LAST_STATE, MAX_BY(ERROR_MESSAGE, IFF(IS_FAILED, SCHEDULED_TIME, NULL)) AS LAST_ERROR,
         MAX(IFF(IS_FAILED, SCHEDULED_TIME, NULL)) AS LAST_FAILURE,
         MAX_BY(THREAD_ID, IFF(THREAD_ID IS NOT NULL, SCHEDULED_TIME, NULL)) AS LAST_THREAD_ID
  FROM MART.V_AUTOMATION_RUN GROUP BY 1
)
SELECT a.TASK_ID, a.KIND, a.OWNER_USER, a.TASK_DATABASE, a.TASK_SCHEMA, a.TASK_NAME,
       COALESCE(NULLIF(a.TITLE, ''), a.TASK_NAME) AS TITLE, a.STATE, a.SCHEDULE, a.TIMEZONE, a.TARGET_AGENT,
       a.PROMPT, a.CREATED, a.LAST_ALTERED, a.DELETED, a.DELETED IS NOT NULL AS IS_DELETED,
       a.LAST_SUSPENDED, a.LAST_SUSPENDED_REASON,
       COALESCE(r.RUNS, 0) AS RUNS, COALESCE(r.SUCCEEDED, 0) AS SUCCEEDED, COALESCE(r.FAILED, 0) AS FAILED,
       COALESCE(r.RUNS_30D, 0) AS RUNS_30D, COALESCE(r.FAILED_30D, 0) AS FAILED_30D,
       DIV0NULL(r.SUCCEEDED, r.SUCCEEDED + r.FAILED) AS SUCCESS_RATE,
       r.P50_MS, r.MAX_MS, r.TOTAL_CREDITS, r.TASK_CREDITS, r.AGENT_CREDITS, r.CODE_CREDITS, r.CREDITS_30D,
       r.FIRST_RUN, r.LAST_RUN, r.LAST_STATE, r.LAST_ERROR, r.LAST_FAILURE, r.LAST_THREAD_ID,
       -- Health: what needs attention
       CASE WHEN a.DELETED IS NOT NULL THEN 'deleted'
            WHEN a.STATE = 'suspended' AND a.LAST_SUSPENDED_REASON ILIKE '%FAIL%' THEN 'auto_suspended'
            WHEN a.STATE = 'suspended' THEN 'paused'
            WHEN r.LAST_STATE IN ('FAILED', 'FAILED_AND_AUTO_SUSPENDED') THEN 'failing'
            WHEN COALESCE(r.FAILED_30D, 0) > 0 THEN 'flaky'
            WHEN r.RUNS IS NULL THEN 'never_run'
            ELSE 'healthy' END AS HEALTH
FROM AGENT_OBS.RAW.AUTOMATION_TASK a
LEFT JOIN runs r ON r.TASK_ID = a.TASK_ID
WHERE a.KIND IN ('COWORK', 'COCO', 'AGENT_SDK');
