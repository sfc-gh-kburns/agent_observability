-- =====================================================================
-- 01_raw.sql  —  schemas, ADMIN control tables, RAW history tables
-- RAW is the system of record: rows are never deleted, so history
-- survives ACCOUNT_USAGE (1 yr) and event-table retention.
-- =====================================================================
USE ROLE AGENT_OBS_INGEST_ROLE;
USE WAREHOUSE <% pipeline_warehouse %>;
USE DATABASE AGENT_OBS;

CREATE SCHEMA IF NOT EXISTS ADMIN COMMENT = 'Pipeline config, logs, procedures, tasks, policies';
CREATE SCHEMA IF NOT EXISTS RAW   COMMENT = 'Append/merge-only full-fidelity copies of source data (never purged)';
CREATE SCHEMA IF NOT EXISTS CORE  COMMENT = 'Conformed facts & dimensions (dynamic tables)';
CREATE SCHEMA IF NOT EXISTS MART  COMMENT = 'App-facing aggregates and views (only schema the app reads)';

-- ADMIN ---------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ADMIN.CONFIG (
  KEY STRING PRIMARY KEY, VALUE STRING, DESCRIPTION STRING,
  UPDATED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());

MERGE INTO ADMIN.CONFIG t USING (
  SELECT * FROM VALUES
   ('USAGE_LOOKBACK_HOURS',  '3',          'Re-read window for ACCOUNT_USAGE agent/cowork usage (latency absorption)'),
   ('EVENTS_LOOKBACK_HOURS', '2',          'Re-read window for AI_OBSERVABILITY_EVENTS'),
   ('QH_LOOKBACK_DAYS',      '2',          'Re-read window for QUERY_HISTORY of agent-generated SQL'),
   ('BACKFILL_START',        '2020-01-01', 'Earliest timestamp read on the initial load'),
   ('CREDIT_PRICE_USD',      '',           'Optional $/AI credit for currency display (blank = credits only)')
  AS s(KEY, VALUE, DESCRIPTION)) s
ON t.KEY = s.KEY
WHEN NOT MATCHED THEN INSERT (KEY, VALUE, DESCRIPTION) VALUES (s.KEY, s.VALUE, s.DESCRIPTION);

CREATE TABLE IF NOT EXISTS ADMIN.LOAD_LOG (
  RUN_ID STRING, STEP STRING, STARTED_AT TIMESTAMP_LTZ, ENDED_AT TIMESTAMP_LTZ,
  ROWS_INSERTED NUMBER, ROWS_UPDATED NUMBER, WATERMARK_FROM TIMESTAMP_LTZ,
  STATUS STRING, MESSAGE STRING);

-- Span-name → category mapping lives in the IMMUTABLE UDF ADMIN.SPAN_CATEGORY (03_core.sql)
-- so dynamic tables can refresh incrementally; ADMIN.V_UNMAPPED_SPANS surfaces new span names.
DROP TABLE IF EXISTS ADMIN.SPAN_CATEGORY_MAP;

-- RAW: usage (CoWork UI + all other interfaces, unified) --------------
CREATE TABLE IF NOT EXISTS RAW.USAGE_TURN (
  REQUEST_ID STRING NOT NULL PRIMARY KEY,
  SOURCE_VIEW STRING,               -- SNOWFLAKE_COWORK_USAGE_HISTORY | CORTEX_AGENT_USAGE_HISTORY | SNOWFLAKE_INTELLIGENCE_USAGE_HISTORY
  START_TIME TIMESTAMP_LTZ, END_TIME TIMESTAMP_LTZ,
  USER_ID NUMBER, USER_NAME STRING, USER_TAGS ARRAY,
  PARENT_REQUEST_ID STRING, THREAD_ID NUMBER,
  COWORK_ID NUMBER, COWORK_NAME STRING, COWORK_TAGS ARRAY,
  AGENT_DATABASE_ID NUMBER, AGENT_DATABASE_NAME STRING, AGENT_SCHEMA_ID NUMBER, AGENT_SCHEMA_NAME STRING,
  AGENT_ID NUMBER, AGENT_NAME STRING, AGENT_TAGS ARRAY,
  TOKEN_CREDITS NUMBER(38,9), TOKENS NUMBER,
  TOKENS_GRANULAR ARRAY, CREDITS_GRANULAR ARRAY, METADATA OBJECT,
  ROW_HASH NUMBER,
  _FIRST_LOADED_AT TIMESTAMP_LTZ, _LAST_LOADED_AT TIMESTAMP_LTZ)
  CLUSTER BY (TO_DATE(START_TIME));

-- RAW: every AI observability event (agents, CoCo, evals, logs) -------
CREATE TABLE IF NOT EXISTS RAW.AI_OBS_EVENTS (
  EVENT_HASH STRING NOT NULL,       -- SHA2 of the full source row (natural keys collide on LOG rows)
  TRACE_ID STRING, RECORD_NAME STRING,   -- promoted for plain-column joins (incremental DT refresh)
  TIMESTAMP TIMESTAMP_NTZ(9), START_TIMESTAMP TIMESTAMP_NTZ(9), OBSERVED_TIMESTAMP TIMESTAMP_NTZ(9),
  TRACE OBJECT, RESOURCE OBJECT, RESOURCE_ATTRIBUTES OBJECT, SCOPE OBJECT, SCOPE_ATTRIBUTES OBJECT,
  RECORD_TYPE STRING, RECORD OBJECT, RECORD_ATTRIBUTES OBJECT, VALUE VARIANT, EXEMPLARS ARRAY,
  _LOADED_AT TIMESTAMP_LTZ)
  CLUSTER BY (TO_DATE(TIMESTAMP));

-- RAW: agent configuration, SCD2 on spec hash -------------------------
CREATE TABLE IF NOT EXISTS RAW.AGENT_CONFIG_HISTORY (
  AGENT_FQN STRING, DATABASE_NAME STRING, SCHEMA_NAME STRING, AGENT_NAME STRING,
  OWNER STRING, COMMENT STRING, PROFILE VARIANT, CREATED_ON TIMESTAMP_LTZ, IS_SECURE BOOLEAN,
  AGENT_SPEC VARIANT, DEFAULT_VERSION_NAME STRING, VERSIONS VARIANT, ALIASES VARIANT,
  CONFIG_HASH STRING,               -- SHA2 over spec + owner/comment/profile/versions/aliases
  VALID_FROM TIMESTAMP_LTZ, VALID_TO TIMESTAMP_LTZ, IS_CURRENT BOOLEAN,
  IS_DROPPED BOOLEAN DEFAULT FALSE, DESCRIBE_ERROR STRING);

-- RAW: semantic views / Cortex Search services daily snapshots -------
CREATE TABLE IF NOT EXISTS RAW.ASSET_SNAPSHOT (
  SNAPSHOT_DATE DATE, ASSET_TYPE STRING, ASSET_FQN STRING,
  DATABASE_NAME STRING, SCHEMA_NAME STRING, ASSET_NAME STRING,
  OWNER STRING, COMMENT STRING, CREATED_ON TIMESTAMP_LTZ,
  VERIFIED_QUERY_COUNT NUMBER, DETAILS VARIANT, _LOADED_AT TIMESTAMP_LTZ);

-- RAW: users (kept after deletion) ------------------------------------
CREATE TABLE IF NOT EXISTS RAW.USERS (
  USER_ID NUMBER PRIMARY KEY, NAME STRING, LOGIN_NAME STRING, DISPLAY_NAME STRING, EMAIL STRING,
  TYPE STRING, DEFAULT_ROLE STRING, DISABLED BOOLEAN, CREATED_ON TIMESTAMP_LTZ, DELETED_ON TIMESTAMP_LTZ,
  LAST_SUCCESS_LOGIN TIMESTAMP_LTZ, DETAILS VARIANT, ROW_HASH NUMBER, _LAST_LOADED_AT TIMESTAMP_LTZ);

-- RAW: warehouse metrics for agent-generated SQL (QUERY_HISTORY ages out)
CREATE TABLE IF NOT EXISTS RAW.AGENT_QUERY_HISTORY (
  QUERY_ID STRING PRIMARY KEY, START_TIME TIMESTAMP_LTZ, END_TIME TIMESTAMP_LTZ,
  WAREHOUSE_NAME STRING, WAREHOUSE_SIZE STRING, ROLE_NAME STRING, USER_NAME STRING,
  EXECUTION_STATUS STRING, ERROR_CODE STRING, ERROR_MESSAGE STRING,
  TOTAL_ELAPSED_TIME NUMBER, EXECUTION_TIME NUMBER, COMPILATION_TIME NUMBER, QUEUED_OVERLOAD_TIME NUMBER,
  BYTES_SCANNED NUMBER, ROWS_PRODUCED NUMBER, PARTITIONS_SCANNED NUMBER, PARTITIONS_TOTAL NUMBER,
  CREDITS_USED_CLOUD_SERVICES FLOAT, QUERY_HASH STRING, _LOADED_AT TIMESTAMP_LTZ);

-- RAW: Cortex Code (CoCo) requests from the three surface usage views ---
-- CoCo runs on the agent runtime but owns no agent object; its traces are
-- passthrough stubs, so these usage views are its system of record.
CREATE TABLE IF NOT EXISTS RAW.CODE_USAGE (
  REQUEST_ID STRING NOT NULL PRIMARY KEY,
  SURFACE STRING,                   -- DESKTOP | SNOWSIGHT | CLI
  USAGE_TIME TIMESTAMP_TZ, USER_ID NUMBER, USER_NAME STRING, USER_TAGS ARRAY,
  PARENT_REQUEST_ID STRING, THREAD_ID NUMBER,
  TOKEN_CREDITS NUMBER(38,9), TOKENS NUMBER,
  TOKENS_GRANULAR OBJECT, CREDITS_GRANULAR OBJECT, METADATA OBJECT,
  ROW_HASH NUMBER, _FIRST_LOADED_AT TIMESTAMP_LTZ, _LAST_LOADED_AT TIMESTAMP_LTZ)
  CLUSTER BY (TO_DATE(USAGE_TIME));

-- RAW: AI SQL function credits, rolled up per day × function × model × user
CREATE TABLE IF NOT EXISTS RAW.AI_FUNCTION_USAGE_DAILY (
  DAY DATE, FUNCTION_NAME STRING, MODEL_NAME STRING, USER_ID NUMBER,
  CALLS NUMBER, CREDITS NUMBER(38,9), _LAST_LOADED_AT TIMESTAMP_LTZ);

-- RAW: user automations (CoWork / CoCo / Agent SDK agent tasks in USER$ databases). See 09_automations.sql.
CREATE TABLE IF NOT EXISTS RAW.AUTOMATION_TASK (
  TASK_ID STRING NOT NULL PRIMARY KEY,
  KIND STRING,                                  -- COWORK | COCO | AGENT_SDK | OTHER
  TASK_DATABASE STRING, TASK_SCHEMA STRING, TASK_NAME STRING, OWNER_USER STRING,
  TASK_OWNER STRING, TITLE STRING,              -- TITLE = task comment (the name shown in CoWork/CoCo)
  STATE STRING, SCHEDULE STRING, TIMEZONE STRING,
  TARGET_AGENT STRING,                          -- DB.SCHEMA.AGENT for agent-run automations
  PROMPT STRING,                                -- content
  DEFINITION STRING,                            -- content
  CREATED TIMESTAMP_LTZ, LAST_ALTERED TIMESTAMP_LTZ, DELETED TIMESTAMP_LTZ,
  LAST_SUSPENDED TIMESTAMP_LTZ, LAST_SUSPENDED_REASON STRING,
  CREATED_BY_USER_ID NUMBER, EXECUTE_AS_USER_ID NUMBER, CONFIG VARIANT,
  ROW_HASH NUMBER, _FIRST_LOADED_AT TIMESTAMP_LTZ, _LAST_LOADED_AT TIMESTAMP_LTZ);

CREATE TABLE IF NOT EXISTS RAW.AUTOMATION_RUN (
  RUN_KEY STRING NOT NULL PRIMARY KEY,          -- SHA2(database, schema, name, scheduled_time, attempt)
  TASK_DATABASE STRING, TASK_SCHEMA STRING, TASK_NAME STRING,
  SCHEDULED_TIME TIMESTAMP_LTZ, QUERY_START_TIME TIMESTAMP_LTZ, COMPLETED_TIME TIMESTAMP_LTZ,
  STATE STRING, ERROR_CODE STRING, ERROR_MESSAGE STRING, RETURN_VALUE STRING,
  QUERY_ID STRING, RUN_ID NUMBER, ATTEMPT_NUMBER NUMBER, SCHEDULED_FROM STRING, SCHEDULED_BY_USER STRING,
  ROW_HASH NUMBER, _LAST_LOADED_AT TIMESTAMP_LTZ)
  CLUSTER BY (TO_DATE(SCHEDULED_TIME));

CREATE TABLE IF NOT EXISTS RAW.AUTOMATION_TASK_CREDITS (
  TASK_ID STRING, TASK_DATABASE STRING, TASK_SCHEMA STRING, TASK_NAME STRING,
  START_TIME TIMESTAMP_LTZ, END_TIME TIMESTAMP_LTZ, CREDITS_USED NUMBER(38,9),
  _LAST_LOADED_AT TIMESTAMP_LTZ);

-- Audit of content-tier reads by the app (R: Auditability)
