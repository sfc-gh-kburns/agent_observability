-- =====================================================================
-- 05_policies.sql — content tier, grants, audit
--  * Content (questions, responses, thinking, SQL, search queries/results,
--    feedback text, raw span attributes) is masked unless the session has
--    AGENT_OBS_CONTENT_ROLE in its hierarchy. Enforced on CORE columns, so
--    it applies to every MART view and any direct query (A5).
--  * The ingest role inherits the content role, so dynamic-table refreshes
--    always see full values.
-- =====================================================================
USE ROLE AGENT_OBS_INGEST_ROLE;
USE WAREHOUSE AGENT_OBS_WH;
USE SCHEMA AGENT_OBS.ADMIN;

CREATE MASKING POLICY IF NOT EXISTS ADMIN.MP_CONTENT_STRING AS (V STRING) RETURNS STRING ->
  CASE WHEN IS_ROLE_IN_SESSION('AGENT_OBS_CONTENT_ROLE') THEN V ELSE NULL END
  COMMENT = 'Agent content tier (text)';
CREATE MASKING POLICY IF NOT EXISTS ADMIN.MP_CONTENT_VARIANT AS (V VARIANT) RETURNS VARIANT ->
  CASE WHEN IS_ROLE_IN_SESSION('AGENT_OBS_CONTENT_ROLE') THEN V ELSE NULL END
  COMMENT = 'Agent content tier (variant)';
CREATE MASKING POLICY IF NOT EXISTS ADMIN.MP_CONTENT_OBJECT AS (V OBJECT) RETURNS OBJECT ->
  CASE WHEN IS_ROLE_IN_SESSION('AGENT_OBS_CONTENT_ROLE') THEN V ELSE NULL END
  COMMENT = 'Agent content tier (object)';
CREATE MASKING POLICY IF NOT EXISTS ADMIN.MP_CONTENT_ARRAY AS (V ARRAY) RETURNS ARRAY ->
  CASE WHEN IS_ROLE_IN_SESSION('AGENT_OBS_CONTENT_ROLE') THEN V ELSE NULL END
  COMMENT = 'Agent content tier (array)';

-- Apply (idempotent: unset then set) ----------------------------------
CREATE OR REPLACE PROCEDURE ADMIN.SP_APPLY_CONTENT_POLICIES()
RETURNS STRING LANGUAGE SQL EXECUTE AS CALLER AS
$$
DECLARE
  n INT DEFAULT 0;
  c CURSOR FOR
    SELECT t, col, pol FROM VALUES
      ('AGENT_OBS.RAW.AI_OBS_EVENTS',         'RECORD_ATTRIBUTES',       'MP_CONTENT_OBJECT'),
      ('AGENT_OBS.RAW.AI_OBS_EVENTS',         'VALUE',                   'MP_CONTENT_VARIANT'),
      ('AGENT_OBS.CORE.EVENT_AGENT',          'ATTRS',                   'MP_CONTENT_OBJECT'),
      ('AGENT_OBS.CORE.EVENT_AGENT',          'EVENT_VALUE',             'MP_CONTENT_VARIANT'),
      ('AGENT_OBS.CORE.FACT_SPAN',            'ATTRS',                   'MP_CONTENT_OBJECT'),
      ('AGENT_OBS.CORE.FACT_TURN',            'FIRST_MESSAGE_IN_THREAD', 'MP_CONTENT_STRING'),
      ('AGENT_OBS.CORE.FACT_TURN',            'QUESTION',                'MP_CONTENT_STRING'),
      ('AGENT_OBS.CORE.FACT_TURN',            'RESPONSE',                'MP_CONTENT_STRING'),
      ('AGENT_OBS.CORE.FACT_TURN',            'THINKING',                'MP_CONTENT_STRING'),
      ('AGENT_OBS.CORE.FACT_TURN',            'SUGGESTED_QUERIES',       'MP_CONTENT_VARIANT'),
      ('AGENT_OBS.CORE.FACT_THREAD',          'FIRST_QUESTION',          'MP_CONTENT_STRING'),
      ('AGENT_OBS.CORE.FACT_SQL_EXECUTION',   'FINAL_SQL',               'MP_CONTENT_STRING'),
      ('AGENT_OBS.CORE.FACT_SQL_EXECUTION',   'ERROR_CORRECTION',        'MP_CONTENT_STRING'),
      ('AGENT_OBS.CORE.FACT_SQL_EXECUTION',   'VALIDATION_ERRORS',       'MP_CONTENT_ARRAY'),
      ('AGENT_OBS.CORE.FACT_SQL_EXECUTION',   'QH_ERROR_MESSAGE',        'MP_CONTENT_STRING'),
      ('AGENT_OBS.CORE.FACT_SEARCH_CALL',     'SEARCH_QUERY',            'MP_CONTENT_STRING'),
      ('AGENT_OBS.CORE.FACT_SEARCH_CALL',     'RESULTS',                 'MP_CONTENT_STRING'),
      ('AGENT_OBS.CORE.FACT_FEEDBACK',        'FEEDBACK_TEXT',           'MP_CONTENT_STRING'),
      ('AGENT_OBS.CORE.FACT_FEEDBACK',        'FEEDBACK_VALUE',          'MP_CONTENT_VARIANT')
    AS v(t, col, pol);
BEGIN
  FOR r IN c DO
    LET kind STRING := IFF(r.t LIKE 'AGENT_OBS.RAW.%', 'TABLE', 'DYNAMIC TABLE');
    BEGIN
      EXECUTE IMMEDIATE 'ALTER ' || kind || ' ' || r.t || ' MODIFY COLUMN ' || r.col || ' UNSET MASKING POLICY';
    EXCEPTION WHEN OTHER THEN NULL;
    END;
    EXECUTE IMMEDIATE 'ALTER ' || kind || ' ' || r.t || ' MODIFY COLUMN ' || r.col
                      || ' SET MASKING POLICY AGENT_OBS.ADMIN.' || r.pol;
    n := n + 1;
  END FOR;
  RETURN n || ' columns protected';
END;
$$;
CALL ADMIN.SP_APPLY_CONTENT_POLICIES();

-- App helpers ------------------------------------------------------------
-- Lets the UI show "content hidden" states instead of empty cells.
CREATE OR REPLACE FUNCTION AGENT_OBS.MART.CAN_VIEW_CONTENT() RETURNS BOOLEAN AS
$$ IS_ROLE_IN_SESSION('AGENT_OBS_CONTENT_ROLE') $$;

-- Audit trail of content-tier views (called by the app when it renders content).
CREATE OR REPLACE PROCEDURE AGENT_OBS.MART.SP_LOG_CONTENT_VIEW(VIEWER STRING, OBJECT_KIND STRING, OBJECT_ID STRING, DETAILS VARIANT)
RETURNS STRING LANGUAGE SQL EXECUTE AS OWNER AS
$$
BEGIN
  INSERT INTO AGENT_OBS.ADMIN.CONTENT_ACCESS_AUDIT (VIEWER, VIEWER_ROLE, OBJECT_KIND, OBJECT_ID, DETAILS)
  SELECT COALESCE(:VIEWER, CURRENT_USER()), CURRENT_ROLE(), :OBJECT_KIND, :OBJECT_ID, :DETAILS;
  RETURN 'logged';
END;
$$;

-- Grants -----------------------------------------------------------------
GRANT USAGE ON DATABASE AGENT_OBS TO ROLE AGENT_OBS_APP_ROLE;
GRANT USAGE ON SCHEMA AGENT_OBS.MART TO ROLE AGENT_OBS_APP_ROLE;
GRANT SELECT ON ALL VIEWS IN SCHEMA AGENT_OBS.MART TO ROLE AGENT_OBS_APP_ROLE;
GRANT SELECT ON ALL DYNAMIC TABLES IN SCHEMA AGENT_OBS.MART TO ROLE AGENT_OBS_APP_ROLE;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA AGENT_OBS.MART TO ROLE AGENT_OBS_APP_ROLE;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA AGENT_OBS.MART TO ROLE AGENT_OBS_APP_ROLE;
GRANT USAGE ON FUNCTION AGENT_OBS.MART.CAN_VIEW_CONTENT() TO ROLE AGENT_OBS_APP_ROLE;
GRANT USAGE ON PROCEDURE AGENT_OBS.MART.SP_LOG_CONTENT_VIEW(STRING, STRING, STRING, VARIANT) TO ROLE AGENT_OBS_APP_ROLE;
-- Content users = app role + content role
GRANT ROLE AGENT_OBS_APP_ROLE TO ROLE AGENT_OBS_CONTENT_ROLE;
