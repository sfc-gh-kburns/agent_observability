-- Config catalog (current) + governance flags + coverage
CREATE OR REPLACE VIEW MART.V_AGENT_CONFIG AS
SELECT a.* EXCLUDE (AGENT_SPEC),
       a.AGENT_SPEC,
       b.BOUND_SEMANTIC_VIEWS, b.BOUND_SEARCH_SERVICES, b.BOUND_FUNCTIONS,
       ch.CONFIG_VERSIONS, ch.LAST_CONFIG_CHANGE,
       a.HAS_WEB_SEARCH                       AS GOV_WEB_SEARCH_ENABLED,
       a.HAS_CODE_EXECUTION                   AS GOV_CODE_EXECUTION_ENABLED,
       (a.OWNER = 'ACCOUNTADMIN')             AS GOV_OWNER_ACCOUNTADMIN,
       (NULLIF(TRIM(a.COMMENT), '') IS NULL)  AS GOV_NO_DESCRIPTION,
       (a.SAMPLE_QUESTION_COUNT = 0)          AS GOV_NO_SAMPLE_QUESTIONS,
       a.IS_BUDGET_UNBOUNDED                  AS GOV_UNBOUNDED_BUDGET,
       (a.DESCRIBE_ERROR IS NOT NULL)         AS GOV_NOT_VISIBLE_TO_INGEST   -- coverage gap (no MONITOR)
FROM AGENT_OBS.CORE.DIM_AGENT a
LEFT JOIN (
  SELECT AGENT_FQN,
         ARRAY_UNIQUE_AGG(IFF(RESOURCE_TYPE IN ('SEMANTIC_VIEW','SEMANTIC_MODEL_FILE'), RESOURCE_FQN, NULL)) BOUND_SEMANTIC_VIEWS,
         ARRAY_UNIQUE_AGG(IFF(RESOURCE_TYPE = 'CORTEX_SEARCH_SERVICE', RESOURCE_FQN, NULL)) BOUND_SEARCH_SERVICES,
         ARRAY_UNIQUE_AGG(IFF(RESOURCE_TYPE = 'FUNCTION_OR_PROCEDURE', RESOURCE_FQN, NULL)) BOUND_FUNCTIONS
  FROM AGENT_OBS.CORE.DIM_AGENT_TOOL WHERE IS_CURRENT GROUP BY 1) b ON b.AGENT_FQN = a.AGENT_FQN
LEFT JOIN (
  SELECT AGENT_FQN, COUNT(*) CONFIG_VERSIONS, MAX(VALID_FROM) LAST_CONFIG_CHANGE
  FROM AGENT_OBS.CORE.DIM_AGENT GROUP BY 1) ch ON ch.AGENT_FQN = a.AGENT_FQN
WHERE a.IS_CURRENT;

-- SCD2 change log with the previous config for diffing in the app
CREATE OR REPLACE VIEW MART.V_AGENT_CONFIG_CHANGES AS
SELECT AGENT_FQN, VALID_FROM AS CHANGED_AT, IS_DROPPED,
       LAG(CONFIG_HASH) OVER (PARTITION BY AGENT_FQN ORDER BY VALID_FROM) IS NULL AS IS_FIRST_SEEN,
       ORCHESTRATION_MODEL, LAG(ORCHESTRATION_MODEL) OVER (PARTITION BY AGENT_FQN ORDER BY VALID_FROM) AS PREV_ORCHESTRATION_MODEL,
       TOOL_COUNT, LAG(TOOL_COUNT) OVER (PARTITION BY AGENT_FQN ORDER BY VALID_FROM) AS PREV_TOOL_COUNT,
       OWNER, LAG(OWNER) OVER (PARTITION BY AGENT_FQN ORDER BY VALID_FROM) AS PREV_OWNER,
       DEFAULT_VERSION_NAME, LAG(DEFAULT_VERSION_NAME) OVER (PARTITION BY AGENT_FQN ORDER BY VALID_FROM) AS PREV_DEFAULT_VERSION_NAME,
       AGENT_SPEC, LAG(AGENT_SPEC) OVER (PARTITION BY AGENT_FQN ORDER BY VALID_FROM) AS PREV_AGENT_SPEC
FROM AGENT_OBS.CORE.DIM_AGENT;

-- Asset catalog: bound (config) vs actually used (spans), orphans
CREATE OR REPLACE VIEW MART.V_ASSET_CATALOG_30D AS
WITH bound AS (
  SELECT UPPER(RESOURCE_FQN) ASSET_KEY, ANY_VALUE(RESOURCE_TYPE) RESOURCE_TYPE,
         COUNT(DISTINCT AGENT_FQN) AGENTS_BOUND, ARRAY_UNIQUE_AGG(AGENT_FQN) AGENTS_BOUND_LIST
  FROM AGENT_OBS.CORE.DIM_AGENT_TOOL WHERE IS_CURRENT AND RESOURCE_FQN IS NOT NULL GROUP BY 1
), used AS (
  SELECT ASSET_KEY, ANY_VALUE(ASSET_TYPE) ASSET_TYPE, COUNT(DISTINCT AGENT_FQN) AGENTS_USING,
         ARRAY_UNIQUE_AGG(AGENT_FQN) AGENTS_USING_LIST, SUM(CALLS) CALLS, SUM(TURNS) TURNS,
         HLL_ESTIMATE(HLL_COMBINE(HLL_IMPORT(USERS_HLL))) USERS,
         SUM(SQL_CALLS) SQL_CALLS, SUM(SQL_ERRORS) SQL_ERRORS, SUM(VERIFIED_QUERY_HITS) VQ_HITS,
         APPROX_PERCENTILE_ESTIMATE(APPROX_PERCENTILE_COMBINE(DURATION_TDIGEST), 0.95) P95_MS
  FROM MART.AGG_ASSET_DAILY WHERE DAY >= CURRENT_DATE() - 30 GROUP BY 1
)
SELECT COALESCE(d.ASSET_KEY, b.ASSET_KEY, u.ASSET_KEY) AS ASSET_KEY,
       COALESCE(d.ASSET_TYPE, b.RESOURCE_TYPE, u.ASSET_TYPE) AS ASSET_TYPE,
       d.OWNER, d.COMMENT, d.VERIFIED_QUERY_COUNT, d.CREATED_ON, d.IS_DROPPED AS ASSET_DROPPED,
       COALESCE(b.AGENTS_BOUND, 0) AGENTS_BOUND, b.AGENTS_BOUND_LIST,
       COALESCE(u.AGENTS_USING, 0) AGENTS_USING, u.AGENTS_USING_LIST,
       COALESCE(u.CALLS, 0) CALLS, COALESCE(u.TURNS, 0) TURNS, COALESCE(u.USERS, 0) USERS,
       DIV0NULL(u.SQL_ERRORS, u.SQL_CALLS) SQL_ERROR_RATE, DIV0NULL(u.VQ_HITS, u.SQL_CALLS) VQ_HIT_RATE, u.P95_MS,
       (COALESCE(u.AGENTS_USING, 0) >= 2) AS IS_SHARED,
       (b.AGENTS_BOUND > 0 AND COALESCE(u.CALLS, 0) = 0) AS IS_BOUND_UNUSED,
       (b.AGENTS_BOUND > 0 AND COALESCE(d.IS_DROPPED, d.ASSET_KEY IS NULL AND b.RESOURCE_TYPE IN ('SEMANTIC_VIEW','CORTEX_SEARCH_SERVICE'))) AS IS_BOUND_BUT_MISSING
FROM (SELECT * FROM AGENT_OBS.CORE.DIM_ASSET) d
FULL OUTER JOIN bound b ON b.ASSET_KEY = d.ASSET_KEY
FULL OUTER JOIN used  u ON u.ASSET_KEY = COALESCE(d.ASSET_KEY, b.ASSET_KEY);

-- Freshness / pipeline health (R-ING-6, Admin screen)
CREATE OR REPLACE VIEW MART.V_FRESHNESS AS
SELECT 'usage' AS SOURCE, MAX(START_TIME)::TIMESTAMP_LTZ AS DATA_THROUGH, MAX(_LAST_LOADED_AT) AS LAST_LOADED_AT, COUNT(*) AS ROWS_
  FROM AGENT_OBS.RAW.USAGE_TURN
UNION ALL SELECT 'events', TO_TIMESTAMP_TZ(TO_VARCHAR(MAX(TIMESTAMP), 'YYYY-MM-DD HH24:MI:SS.FF3') || ' +00:00',
                                           'YYYY-MM-DD HH24:MI:SS.FF3 TZH:TZM')::TIMESTAMP_LTZ, MAX(_LOADED_AT), COUNT(*)
  FROM AGENT_OBS.RAW.AI_OBS_EVENTS
UNION ALL SELECT 'agent_config', MAX(VALID_FROM), MAX(VALID_FROM), COUNT_IF(IS_CURRENT) FROM AGENT_OBS.RAW.AGENT_CONFIG_HISTORY
UNION ALL SELECT 'assets', MAX(SNAPSHOT_DATE)::TIMESTAMP_LTZ, MAX(_LOADED_AT), COUNT_IF(SNAPSHOT_DATE = (SELECT MAX(SNAPSHOT_DATE) FROM AGENT_OBS.RAW.ASSET_SNAPSHOT))
  FROM AGENT_OBS.RAW.ASSET_SNAPSHOT
UNION ALL SELECT 'query_history', MAX(START_TIME), MAX(_LOADED_AT), COUNT(*) FROM AGENT_OBS.RAW.AGENT_QUERY_HISTORY;

CREATE OR REPLACE VIEW MART.V_PIPELINE_RUNS AS
SELECT * FROM AGENT_OBS.ADMIN.LOAD_LOG WHERE STARTED_AT >= DATEADD(day, -14, CURRENT_TIMESTAMP());

