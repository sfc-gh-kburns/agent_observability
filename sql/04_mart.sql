-- Trace waterfall: offset/depth relative to the turn root. span_id is NOT
-- unique (planning spans can share it with the tool span) → key = EVENT_HASH.
-- IS_ORPHAN: parent never arrived (best-effort delivery) or is the caller's
-- external trace context (API clients) → render under the root.
CREATE OR REPLACE VIEW MART.V_SPAN AS
SELECT s.*,
       DATEDIFF(millisecond, MIN(s.START_TS_UTC) OVER (PARTITION BY s.TRACE_ID), s.START_TS_UTC) AS OFFSET_MS,
       CASE WHEN s.SPAN_CATEGORY = 'root' OR s.PARENT_SPAN_ID IS NULL THEN 0
            WHEN s.SPAN_CATEGORY = 'sql_exec' THEN 2 ELSE 1 END                                  AS DEPTH,
       (s.PARENT_SPAN_ID IS NOT NULL AND p.SPAN_ID IS NULL)                                      AS IS_ORPHAN
FROM AGENT_OBS.CORE.FACT_SPAN s
LEFT JOIN (SELECT DISTINCT TRACE_ID, SPAN_ID FROM AGENT_OBS.CORE.FACT_SPAN) p
  ON p.TRACE_ID = s.TRACE_ID AND p.SPAN_ID = s.PARENT_SPAN_ID;

