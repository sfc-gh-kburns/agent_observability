-- ---------------------------------------------------------------------
-- Daily aggregates (all additive or sketch-based so any window can be
-- re-aggregated by the app without double counting)
-- ---------------------------------------------------------------------
CREATE OR REPLACE DYNAMIC TABLE MART.AGG_AGENT_DAILY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = AGENT_OBS_WH REFRESH_MODE = FULL
  COMMENT = 'Turn-level KPIs by day × agent × interface × version × model-free dims'
AS
SELECT
  TO_DATE(START_TIME_UTC) AS DAY,
  COALESCE(AGENT_FQN, '(no agent object)') AS AGENT_FQN,
  AGENT_DATABASE_NAME, AGENT_SCHEMA_NAME, AGENT_NAME,
  SOURCE, INTERFACE, COWORK_NAME, AGENT_VERSION_NAME,
  COUNT(*)                                   AS TURNS,
  COUNT(DISTINCT THREAD_ID)                  AS THREADS,
  COUNT(DISTINCT USER_ID)                    AS USERS,
  HLL_EXPORT(HLL_ACCUMULATE(USER_ID))        AS USERS_HLL,       -- re-aggregate distinct users across days
  HLL_EXPORT(HLL_ACCUMULATE(THREAD_ID))      AS THREADS_HLL,
  SUM(COMBINED_CREDITS)                      AS COMBINED_CREDITS,
  SUM(TOKEN_CREDITS)                         AS TOKEN_CREDITS,
  SUM(AI_FUNCTIONS_CREDITS)                  AS AI_FUNCTIONS_CREDITS,
  SUM(SQL_QUERY_CREDITS)                     AS SQL_QUERY_CREDITS,
  SUM(TOKENS)                                AS TOKENS,
  SUM(TOKENS_INPUT)                          AS TOKENS_INPUT,
  SUM(TOKENS_OUTPUT)                         AS TOKENS_OUTPUT,
  SUM(TOKENS_CACHE_READ)                     AS TOKENS_CACHE_READ,
  SUM(TOKENS_CACHE_WRITE)                    AS TOKENS_CACHE_WRITE,
  COUNT_IF(IS_SUCCESS)                       AS SUCCESS_TURNS,
  COUNT_IF(HAS_TRACE)                        AS TRACED_TURNS,
  COUNT_IF(HAS_USAGE)                        AS BILLED_TURNS,
  SUM(DURATION_MS)                           AS SUM_DURATION_MS,
  COUNT(DURATION_MS)                         AS N_DURATION,
  APPROX_PERCENTILE_ACCUMULATE(DURATION_MS)  AS DURATION_TDIGEST,  -- re-aggregate p50/p95 across days
  SUM(PLANNING_STEPS)                        AS PLANNING_STEPS,
  SUM(TOOL_CALLS)                            AS TOOL_CALLS,
  SUM(SQL_CALLS)                             AS SQL_CALLS,
  SUM(SQL_ERRORS)                            AS SQL_ERRORS,
  SUM(VERIFIED_QUERY_HITS)                   AS VERIFIED_QUERY_HITS,
  SUM(SEARCH_CALLS)                          AS SEARCH_CALLS,
  SUM(WEB_SEARCH_CALLS)                      AS WEB_SEARCH_CALLS,
  SUM(CODE_EXEC_CALLS)                       AS CODE_EXEC_CALLS,
  MAX(END_TIME_UTC)                          AS LAST_TURN_AT_UTC
FROM AGENT_OBS.CORE.FACT_TURN
GROUP BY ALL;

CREATE OR REPLACE DYNAMIC TABLE MART.AGG_FEEDBACK_DAILY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = AGENT_OBS_WH REFRESH_MODE = FULL
AS
SELECT TO_DATE(f.FEEDBACK_TS_UTC) AS DAY,
       COALESCE(t.AGENT_FQN, '"' || f.AGENT_DATABASE_NAME || '"."' || f.AGENT_SCHEMA_NAME || '"."' || f.AGENT_NAME || '"') AS AGENT_FQN,
       COALESCE(t.INTERFACE, 'unknown') AS INTERFACE,
       COUNT(*) AS FEEDBACK_COUNT, COUNT_IF(f.IS_POSITIVE) AS POSITIVE, COUNT_IF(NOT f.IS_POSITIVE) AS NEGATIVE,
       COUNT(DISTINCT f.TURN_ID) AS TURNS_WITH_FEEDBACK
FROM AGENT_OBS.CORE.FACT_FEEDBACK f
LEFT JOIN AGENT_OBS.CORE.FACT_TURN t ON t.TURN_ID = f.TURN_ID
GROUP BY ALL;

CREATE OR REPLACE DYNAMIC TABLE MART.AGG_MODEL_DAILY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = AGENT_OBS_WH REFRESH_MODE = FULL
  COMMENT = 'Authoritative tokens/credits by day × agent × service type × model'
AS
SELECT TO_DATE(t.START_TIME_UTC) AS DAY, COALESCE(t.AGENT_FQN, '(no agent object)') AS AGENT_FQN, t.INTERFACE,
       m.SERVICE_TYPE, m.MODEL,
       COUNT(DISTINCT m.REQUEST_ID) AS TURNS,
       SUM(m.TOKENS_INPUT) AS TOKENS_INPUT, SUM(m.TOKENS_OUTPUT) AS TOKENS_OUTPUT,
       SUM(m.TOKENS_CACHE_READ) AS TOKENS_CACHE_READ, SUM(m.TOKENS_CACHE_WRITE) AS TOKENS_CACHE_WRITE,
       SUM(m.TOKENS_TOTAL) AS TOKENS_TOTAL, SUM(m.CREDITS_TOTAL) AS CREDITS,
       SUM(m.CREDITS_INPUT) AS CREDITS_INPUT, SUM(m.CREDITS_OUTPUT) AS CREDITS_OUTPUT,
       SUM(m.CREDITS_CACHE_READ) AS CREDITS_CACHE_READ, SUM(m.CREDITS_CACHE_WRITE) AS CREDITS_CACHE_WRITE
FROM AGENT_OBS.CORE.FACT_TURN_MODEL_USAGE m
JOIN AGENT_OBS.CORE.FACT_TURN t ON t.REQUEST_ID = m.REQUEST_ID
GROUP BY ALL;

CREATE OR REPLACE DYNAMIC TABLE MART.AGG_TOOL_DAILY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = AGENT_OBS_WH REFRESH_MODE = FULL
  COMMENT = 'Tool-call spans by day × agent × category × tool'
AS
SELECT TO_DATE(s.START_TS_UTC) AS DAY, COALESCE(t.AGENT_FQN, '(no agent object)') AS AGENT_FQN,
       s.SPAN_CATEGORY, COALESCE(s.TOOL_NAME, s.SPAN_NAME_NORM) AS TOOL_NAME,
       COUNT(*) AS CALLS, COUNT(DISTINCT s.TRACE_ID) AS TURNS, COUNT_IF(s.IS_ERROR OR s.IS_SQL_ERROR) AS ERRORS,
       SUM(s.DURATION_MS) AS SUM_DURATION_MS, APPROX_PERCENTILE_ACCUMULATE(s.DURATION_MS) AS DURATION_TDIGEST
FROM AGENT_OBS.CORE.FACT_SPAN s
LEFT JOIN (SELECT TRACE_ID, ANY_VALUE(AGENT_FQN) AS AGENT_FQN, ANY_VALUE(USER_ID) AS USER_ID FROM AGENT_OBS.CORE.FACT_TURN WHERE TRACE_ID IS NOT NULL GROUP BY 1) t ON t.TRACE_ID = s.TRACE_ID   -- one row per trace (traces can span turns)
WHERE s.SPAN_CATEGORY IN ('sql','analyst','semantic_context','search','chart','code_exec','skill','custom',
                          'web_search','mcp','subagent','agent_task')
GROUP BY ALL;

CREATE OR REPLACE DYNAMIC TABLE MART.AGG_PLANNING_DEPTH
  TARGET_LAG = DOWNSTREAM WAREHOUSE = AGENT_OBS_WH REFRESH_MODE = FULL
AS
SELECT TO_DATE(START_TIME_UTC) AS DAY, COALESCE(AGENT_FQN, '(no agent object)') AS AGENT_FQN,
       COALESCE(PLANNING_STEPS, 0) AS PLANNING_STEPS, COUNT(*) AS TURNS
FROM AGENT_OBS.CORE.FACT_TURN WHERE HAS_TRACE AND NOT IS_SHARED_TRACE GROUP BY ALL;

-- Asset usage (semantic views / search services / semantic model files)
-- resolving tool-name-only references through the agent's tool config.
CREATE OR REPLACE DYNAMIC TABLE MART.AGG_ASSET_DAILY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = AGENT_OBS_WH REFRESH_MODE = FULL
AS
WITH cfg AS (
  SELECT AGENT_FQN, TOOL_NAME, RESOURCE_FQN, RESOURCE_TYPE
  FROM AGENT_OBS.CORE.DIM_AGENT_TOOL WHERE IS_CURRENT AND RESOURCE_FQN IS NOT NULL
), s AS (
  SELECT s.*, t.AGENT_FQN, t.USER_ID FROM AGENT_OBS.CORE.FACT_SPAN s
  JOIN (SELECT TRACE_ID, ANY_VALUE(AGENT_FQN) AS AGENT_FQN, ANY_VALUE(USER_ID) AS USER_ID FROM AGENT_OBS.CORE.FACT_TURN WHERE TRACE_ID IS NOT NULL GROUP BY 1) t ON t.TRACE_ID = s.TRACE_ID
  WHERE s.SPAN_CATEGORY IN ('sql','analyst','semantic_context','search')
)
SELECT TO_DATE(s.START_TS_UTC) AS DAY, s.AGENT_FQN,
       UPPER(COALESCE(IFF(s.RESOURCE_FQN LIKE '%.%', s.RESOURCE_FQN, NULL), c.RESOURCE_FQN, s.RESOURCE_FQN)) AS ASSET_KEY,
       CASE WHEN s.SPAN_CATEGORY = 'search' THEN 'CORTEX_SEARCH_SERVICE'
            WHEN COALESCE(s.RESOURCE_FQN, c.RESOURCE_FQN) LIKE '@%' THEN 'SEMANTIC_MODEL_FILE'
            ELSE 'SEMANTIC_VIEW' END AS ASSET_TYPE,
       COUNT(*) AS CALLS, COUNT(DISTINCT s.TRACE_ID) AS TURNS, COUNT(DISTINCT s.USER_ID) AS USERS,
       HLL_EXPORT(HLL_ACCUMULATE(s.USER_ID)) AS USERS_HLL,
       COUNT_IF(s.SPAN_CATEGORY = 'sql') AS SQL_CALLS, COUNT_IF(s.IS_SQL_ERROR) AS SQL_ERRORS,
       COUNT_IF(s.SPAN_CATEGORY = 'sql' AND s.VERIFIED_QUERY_USED) AS VERIFIED_QUERY_HITS,
       COUNT_IF(s.IS_ERROR) AS ERROR_SPANS,
       SUM(s.DURATION_MS) AS SUM_DURATION_MS, APPROX_PERCENTILE_ACCUMULATE(s.DURATION_MS) AS DURATION_TDIGEST
FROM s
LEFT JOIN cfg c ON c.AGENT_FQN = s.AGENT_FQN AND UPPER(c.TOOL_NAME) = UPPER(s.TOOL_NAME)
WHERE COALESCE(s.RESOURCE_FQN, c.RESOURCE_FQN) IS NOT NULL
GROUP BY ALL;

-- ---------------------------------------------------------------------
-- Portfolio / leaderboard (current-state views over aggregates)
-- ---------------------------------------------------------------------
CREATE OR REPLACE VIEW MART.V_AGENT_LEADERBOARD_30D COMMENT = 'Agent leaderboard, last 30 days vs prior 30 days, with flags' AS
WITH cur AS (
  SELECT AGENT_FQN, SUM(TURNS) TURNS, HLL_ESTIMATE(HLL_COMBINE(HLL_IMPORT(USERS_HLL))) USERS,
         SUM(COMBINED_CREDITS) CREDITS, SUM(SUCCESS_TURNS) SUCCESS, SUM(SQL_CALLS) SQL_CALLS, SUM(SQL_ERRORS) SQL_ERRORS,
         APPROX_PERCENTILE_ESTIMATE(APPROX_PERCENTILE_COMBINE(DURATION_TDIGEST), 0.95) P95_MS,
         APPROX_PERCENTILE_ESTIMATE(APPROX_PERCENTILE_COMBINE(DURATION_TDIGEST), 0.50) P50_MS,
         MAX(LAST_TURN_AT_UTC) LAST_USED_UTC
  FROM MART.AGG_AGENT_DAILY WHERE DAY >= CURRENT_DATE() - 30 GROUP BY 1
), prev AS (
  SELECT AGENT_FQN, SUM(TURNS) TURNS, SUM(COMBINED_CREDITS) CREDITS, SUM(SUCCESS_TURNS) SUCCESS
  FROM MART.AGG_AGENT_DAILY WHERE DAY >= CURRENT_DATE() - 60 AND DAY < CURRENT_DATE() - 30 GROUP BY 1
), fb AS (
  SELECT AGENT_FQN, SUM(POSITIVE) POS, SUM(FEEDBACK_COUNT) N FROM MART.AGG_FEEDBACK_DAILY
  WHERE DAY >= CURRENT_DATE() - 30 GROUP BY 1
), spark AS (
  SELECT AGENT_FQN, ARRAY_AGG(OBJECT_CONSTRUCT('day', DAY, 'turns', T)) WITHIN GROUP (ORDER BY DAY) SPARKLINE
  FROM (SELECT AGENT_FQN, DAY, SUM(TURNS) T FROM MART.AGG_AGENT_DAILY WHERE DAY >= CURRENT_DATE() - 30 GROUP BY 1,2)
  GROUP BY 1
), last_any AS (
  SELECT AGENT_FQN, MAX(LAST_TURN_AT_UTC) LAST_USED_UTC FROM MART.AGG_AGENT_DAILY GROUP BY 1
), agents AS (
  SELECT AGENT_FQN, DISPLAY_NAME, OWNER, IS_DROPPED FROM AGENT_OBS.CORE.DIM_AGENT WHERE IS_CURRENT
  UNION ALL
  SELECT DISTINCT AGENT_FQN, AGENT_FQN, NULL, NULL FROM MART.AGG_AGENT_DAILY
  WHERE AGENT_FQN NOT IN (SELECT AGENT_FQN FROM AGENT_OBS.CORE.DIM_AGENT WHERE IS_CURRENT)
), base AS (
  SELECT a.AGENT_FQN, a.DISPLAY_NAME, a.OWNER, COALESCE(a.IS_DROPPED, FALSE) IS_DROPPED,
         COALESCE(c.TURNS,0) TURNS, COALESCE(c.USERS,0) USERS, COALESCE(c.CREDITS,0) CREDITS,
         DIV0NULL(c.CREDITS, c.TURNS) CREDITS_PER_TURN, DIV0NULL(c.SUCCESS, c.TURNS) SUCCESS_RATE,
         DIV0NULL(c.SQL_ERRORS, c.SQL_CALLS) SQL_ERROR_RATE, DIV0NULL(f.POS, f.N) FEEDBACK_POSITIVE_RATE, f.N FEEDBACK_COUNT,
         c.P50_MS, c.P95_MS, l.LAST_USED_UTC, s.SPARKLINE,
         p.TURNS PREV_TURNS, p.CREDITS PREV_CREDITS, DIV0NULL(p.SUCCESS, p.TURNS) PREV_SUCCESS_RATE
  FROM agents a
  LEFT JOIN cur c ON c.AGENT_FQN = a.AGENT_FQN LEFT JOIN prev p ON p.AGENT_FQN = a.AGENT_FQN
  LEFT JOIN fb f ON f.AGENT_FQN = a.AGENT_FQN LEFT JOIN spark s ON s.AGENT_FQN = a.AGENT_FQN
  LEFT JOIN last_any l ON l.AGENT_FQN = a.AGENT_FQN
)
SELECT b.*,
       (b.TURNS = 0)                                                        AS FLAG_IDLE,
       -- cost outlier: credits/turn > 2× the median of active agents
       COALESCE(b.CREDITS_PER_TURN > 2 * MEDIAN(IFF(b.TURNS >= 5, b.CREDITS_PER_TURN, NULL)) OVER (), FALSE) AS FLAG_COST_OUTLIER,
       -- quality regression: success rate fell ≥10 pts vs prior period with enough volume
       COALESCE(b.TURNS >= 10 AND b.PREV_TURNS >= 10 AND b.SUCCESS_RATE <= b.PREV_SUCCESS_RATE - 0.10, FALSE) AS FLAG_QUALITY_REGRESSION
FROM base b;

CREATE OR REPLACE VIEW MART.V_ADOPTION_FUNNEL_30D AS
WITH u AS (
  SELECT AGENT_FQN, HLL_ESTIMATE(HLL_COMBINE(HLL_IMPORT(USERS_HLL))) USERS,
         COUNT(DISTINCT DATE_TRUNC('week', DAY)) ACTIVE_WEEKS
  FROM MART.AGG_AGENT_DAILY WHERE DAY >= CURRENT_DATE() - 30 GROUP BY 1
)
SELECT (SELECT COUNT(*) FROM AGENT_OBS.CORE.DIM_AGENT WHERE IS_CURRENT AND NOT IS_DROPPED) AS PROVISIONED,
       COUNT_IF(USERS >= 1) AS USED, COUNT_IF(USERS >= 5) AS USED_BY_5_PLUS, COUNT_IF(ACTIVE_WEEKS >= 4) AS USED_WEEKLY
FROM u WHERE AGENT_FQN <> '(no agent object)';

