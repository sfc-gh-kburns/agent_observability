-- Helper: config lookup ------------------------------------------------
CREATE OR REPLACE FUNCTION ADMIN.CFG(K STRING) RETURNS STRING AS
$$ SELECT ANY_VALUE(VALUE) FROM AGENT_OBS.ADMIN.CONFIG WHERE KEY = K $$;

CREATE OR REPLACE PROCEDURE ADMIN.SP_LOG(RUN_ID STRING, STEP STRING, STARTED TIMESTAMP_LTZ,
  INS NUMBER, UPD NUMBER, WM TIMESTAMP_LTZ, STATUS STRING, MSG STRING)
RETURNS STRING LANGUAGE SQL EXECUTE AS CALLER AS
$$
BEGIN
  INSERT INTO AGENT_OBS.ADMIN.LOAD_LOG
  VALUES (:RUN_ID, :STEP, :STARTED, CURRENT_TIMESTAMP(), :INS, :UPD, :WM, :STATUS, :MSG);
  RETURN STATUS;
END;
$$;

-- 1. Usage views → RAW.USAGE_TURN (MERGE on REQUEST_ID) ---------------
CREATE OR REPLACE PROCEDURE ADMIN.SP_LOAD_USAGE()
RETURNS VARIANT LANGUAGE SQL EXECUTE AS CALLER AS
$$
DECLARE
  run_id STRING DEFAULT UUID_STRING();
  started TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP();
  wm TIMESTAMP_LTZ;
  ins NUMBER DEFAULT 0; upd NUMBER DEFAULT 0;
BEGIN
  SELECT COALESCE(DATEADD(hour, -AGENT_OBS.ADMIN.CFG('USAGE_LOOKBACK_HOURS')::INT, MAX(START_TIME)),
                  AGENT_OBS.ADMIN.CFG('BACKFILL_START')::TIMESTAMP_LTZ)
    INTO :wm FROM AGENT_OBS.RAW.USAGE_TURN;

  MERGE INTO AGENT_OBS.RAW.USAGE_TURN t USING (
    WITH src AS (
      SELECT 'SNOWFLAKE_COWORK_USAGE_HISTORY' SOURCE_VIEW, 1 PRIO, START_TIME, END_TIME, USER_ID, USER_NAME, USER_TAGS,
             REQUEST_ID, PARENT_REQUEST_ID, THREAD_ID, SNOWFLAKE_COWORK_ID COWORK_ID, SNOWFLAKE_COWORK_NAME COWORK_NAME,
             SNOWFLAKE_COWORK_TAGS COWORK_TAGS, AGENT_DATABASE_ID, AGENT_DATABASE_NAME, AGENT_SCHEMA_ID, AGENT_SCHEMA_NAME,
             AGENT_ID, AGENT_NAME, AGENT_TAGS, TOKEN_CREDITS, TOKENS, TOKENS_GRANULAR, CREDITS_GRANULAR, METADATA
      FROM SNOWFLAKE.ACCOUNT_USAGE.SNOWFLAKE_COWORK_USAGE_HISTORY WHERE START_TIME >= :wm
      UNION ALL
      SELECT 'CORTEX_AGENT_USAGE_HISTORY', 1, START_TIME, END_TIME, USER_ID, USER_NAME, USER_TAGS,
             REQUEST_ID, PARENT_REQUEST_ID, THREAD_ID, NULL, NULL, NULL, AGENT_DATABASE_ID, AGENT_DATABASE_NAME,
             AGENT_SCHEMA_ID, AGENT_SCHEMA_NAME, AGENT_ID, AGENT_NAME, AGENT_TAGS, TOKEN_CREDITS, TOKENS,
             TOKENS_GRANULAR, CREDITS_GRANULAR, METADATA
      FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AGENT_USAGE_HISTORY WHERE START_TIME >= :wm
      UNION ALL  -- legacy alias of the CoWork view: only rows CoWork doesn't have
      SELECT 'SNOWFLAKE_INTELLIGENCE_USAGE_HISTORY', 2, START_TIME, END_TIME, USER_ID, USER_NAME, USER_TAGS,
             REQUEST_ID, PARENT_REQUEST_ID, THREAD_ID, SNOWFLAKE_INTELLIGENCE_ID, SNOWFLAKE_INTELLIGENCE_NAME,
             SNOWFLAKE_INTELLIGENCE_TAGS, AGENT_DATABASE_ID, AGENT_DATABASE_NAME, AGENT_SCHEMA_ID, AGENT_SCHEMA_NAME,
             AGENT_ID, AGENT_NAME, AGENT_TAGS, TOKEN_CREDITS, TOKENS, TOKENS_GRANULAR, CREDITS_GRANULAR, METADATA
      FROM SNOWFLAKE.ACCOUNT_USAGE.SNOWFLAKE_INTELLIGENCE_USAGE_HISTORY WHERE START_TIME >= :wm
    )
    SELECT * EXCLUDE PRIO,
           HASH(START_TIME, END_TIME, USER_ID, PARENT_REQUEST_ID, THREAD_ID, AGENT_ID, TOKEN_CREDITS, TOKENS,
                TOKENS_GRANULAR, CREDITS_GRANULAR, METADATA, USER_TAGS, AGENT_TAGS) ROW_HASH
    FROM src QUALIFY ROW_NUMBER() OVER (PARTITION BY REQUEST_ID ORDER BY PRIO) = 1
  ) s ON t.REQUEST_ID = s.REQUEST_ID
  WHEN MATCHED AND t.ROW_HASH <> s.ROW_HASH THEN UPDATE SET
    SOURCE_VIEW = s.SOURCE_VIEW, START_TIME = s.START_TIME, END_TIME = s.END_TIME, USER_ID = s.USER_ID,
    USER_NAME = s.USER_NAME, USER_TAGS = s.USER_TAGS, PARENT_REQUEST_ID = s.PARENT_REQUEST_ID, THREAD_ID = s.THREAD_ID,
    COWORK_ID = s.COWORK_ID, COWORK_NAME = s.COWORK_NAME, COWORK_TAGS = s.COWORK_TAGS,
    AGENT_DATABASE_ID = s.AGENT_DATABASE_ID, AGENT_DATABASE_NAME = s.AGENT_DATABASE_NAME,
    AGENT_SCHEMA_ID = s.AGENT_SCHEMA_ID, AGENT_SCHEMA_NAME = s.AGENT_SCHEMA_NAME, AGENT_ID = s.AGENT_ID,
    AGENT_NAME = s.AGENT_NAME, AGENT_TAGS = s.AGENT_TAGS, TOKEN_CREDITS = s.TOKEN_CREDITS, TOKENS = s.TOKENS,
    TOKENS_GRANULAR = s.TOKENS_GRANULAR, CREDITS_GRANULAR = s.CREDITS_GRANULAR, METADATA = s.METADATA,
    ROW_HASH = s.ROW_HASH, _LAST_LOADED_AT = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN INSERT VALUES (
    s.REQUEST_ID, s.SOURCE_VIEW, s.START_TIME, s.END_TIME, s.USER_ID, s.USER_NAME, s.USER_TAGS,
    s.PARENT_REQUEST_ID, s.THREAD_ID, s.COWORK_ID, s.COWORK_NAME, s.COWORK_TAGS,
    s.AGENT_DATABASE_ID, s.AGENT_DATABASE_NAME, s.AGENT_SCHEMA_ID, s.AGENT_SCHEMA_NAME, s.AGENT_ID, s.AGENT_NAME,
    s.AGENT_TAGS, s.TOKEN_CREDITS, s.TOKENS, s.TOKENS_GRANULAR, s.CREDITS_GRANULAR, s.METADATA, s.ROW_HASH,
    CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP());

  SELECT "number of rows inserted", "number of rows updated" INTO :ins, :upd FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));
  CALL AGENT_OBS.ADMIN.SP_LOG(:run_id, 'USAGE', :started, :ins, :upd, :wm, 'OK', NULL);
  RETURN OBJECT_CONSTRUCT('step','USAGE','inserted',ins,'updated',upd,'from',wm);
EXCEPTION WHEN OTHER THEN
  CALL AGENT_OBS.ADMIN.SP_LOG(:run_id, 'USAGE', :started, 0, 0, :wm, 'FAILED', :SQLERRM);
  RAISE;
END;
$$;

-- 2. AI_OBSERVABILITY_EVENTS → RAW.AI_OBS_EVENTS (append, dedupe on row hash)
CREATE OR REPLACE PROCEDURE ADMIN.SP_LOAD_EVENTS()
RETURNS VARIANT LANGUAGE SQL EXECUTE AS CALLER AS
$$
DECLARE
  run_id STRING DEFAULT UUID_STRING();
  started TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP();
  wm TIMESTAMP_NTZ;
  ins NUMBER DEFAULT 0;
BEGIN
  SELECT COALESCE(DATEADD(hour, -AGENT_OBS.ADMIN.CFG('EVENTS_LOOKBACK_HOURS')::INT, MAX(TIMESTAMP)),
                  AGENT_OBS.ADMIN.CFG('BACKFILL_START')::TIMESTAMP_NTZ)
    INTO :wm FROM AGENT_OBS.RAW.AI_OBS_EVENTS;

  INSERT INTO AGENT_OBS.RAW.AI_OBS_EVENTS (EVENT_HASH, TRACE_ID, RECORD_NAME, TIMESTAMP, START_TIMESTAMP,
    OBSERVED_TIMESTAMP, TRACE, RESOURCE, RESOURCE_ATTRIBUTES, SCOPE, SCOPE_ATTRIBUTES, RECORD_TYPE, RECORD,
    RECORD_ATTRIBUTES, VALUE, EXEMPLARS, _LOADED_AT)
  WITH src AS (
    SELECT SHA2(CONCAT_WS('|',
             NVL(TO_VARCHAR(TIMESTAMP,'YYYY-MM-DD HH24:MI:SS.FF9'),'~'),
             NVL(TO_VARCHAR(START_TIMESTAMP,'YYYY-MM-DD HH24:MI:SS.FF9'),'~'),
             NVL(TO_VARCHAR(OBSERVED_TIMESTAMP,'YYYY-MM-DD HH24:MI:SS.FF9'),'~'),
             NVL(TO_JSON(TRACE),'~'), NVL(TO_JSON(RESOURCE),'~'), NVL(TO_JSON(RESOURCE_ATTRIBUTES),'~'),
             NVL(TO_JSON(SCOPE),'~'), NVL(TO_JSON(SCOPE_ATTRIBUTES),'~'), NVL(RECORD_TYPE,'~'),
             NVL(TO_JSON(RECORD),'~'), NVL(TO_JSON(RECORD_ATTRIBUTES),'~'), NVL(TO_JSON(VALUE),'~'),
             NVL(TO_JSON(EXEMPLARS),'~')), 256) EVENT_HASH,
           TRACE:trace_id::STRING TRACE_ID, RECORD:name::STRING RECORD_NAME,
           TIMESTAMP, START_TIMESTAMP, OBSERVED_TIMESTAMP, TRACE, RESOURCE, RESOURCE_ATTRIBUTES, SCOPE,
           SCOPE_ATTRIBUTES, RECORD_TYPE, RECORD, RECORD_ATTRIBUTES, VALUE, EXEMPLARS
    FROM SNOWFLAKE.LOCAL.AI_OBSERVABILITY_EVENTS
    WHERE TIMESTAMP >= :wm
  )
  SELECT s.*, CURRENT_TIMESTAMP() FROM src s
  WHERE NOT EXISTS (SELECT 1 FROM AGENT_OBS.RAW.AI_OBS_EVENTS r
                    WHERE r.TIMESTAMP >= DATEADD(minute, -5, :wm) AND r.EVENT_HASH = s.EVENT_HASH)
  QUALIFY ROW_NUMBER() OVER (PARTITION BY s.EVENT_HASH ORDER BY s.TIMESTAMP) = 1;

  ins := SQLROWCOUNT;
  CALL AGENT_OBS.ADMIN.SP_LOG(:run_id, 'EVENTS', :started, :ins, 0, :wm::TIMESTAMP_LTZ, 'OK', NULL);
  RETURN OBJECT_CONSTRUCT('step','EVENTS','inserted',ins,'from',wm);
EXCEPTION WHEN OTHER THEN
  CALL AGENT_OBS.ADMIN.SP_LOG(:run_id, 'EVENTS', :started, 0, 0, :wm::TIMESTAMP_LTZ, 'FAILED', :SQLERRM);
  RAISE;
END;
$$;

-- 3. Agent config snapshot (SHOW + DESCRIBE) → SCD2 RAW.AGENT_CONFIG_HISTORY
CREATE OR REPLACE PROCEDURE ADMIN.SP_LOAD_AGENT_CONFIG()
RETURNS VARIANT LANGUAGE SQL EXECUTE AS CALLER AS
$$
DECLARE
  run_id STRING DEFAULT UUID_STRING();
  started TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP();
  now_ts TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP();
  ins NUMBER DEFAULT 0; closed NUMBER DEFAULT 0; dropped NUMBER DEFAULT 0; errs NUMBER DEFAULT 0;
  fqn STRING;
  c CURSOR FOR SELECT AGENT_FQN FROM _AGENTS;
BEGIN
  SHOW AGENTS IN ACCOUNT;
  CREATE OR REPLACE TEMPORARY TABLE _AGENTS AS
    SELECT '"' || REPLACE("database_name",'"','""') || '"."' || REPLACE("schema_name",'"','""') || '"."'
             || REPLACE("name",'"','""') || '"' AGENT_FQN,
           "database_name" DATABASE_NAME, "schema_name" SCHEMA_NAME, "name" AGENT_NAME, "owner" OWNER,
           "comment" COMMENT, TRY_PARSE_JSON("profile") PROFILE, "created_on" CREATED_ON,
           TRY_TO_BOOLEAN("is_secure"::STRING) IS_SECURE
    FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

  CREATE OR REPLACE TEMPORARY TABLE _DESC (AGENT_FQN STRING, D VARIANT, ERR STRING);
  FOR r IN c DO
    fqn := r.AGENT_FQN;
    BEGIN
      EXECUTE IMMEDIATE 'DESCRIBE AGENT ' || fqn;
      INSERT INTO _DESC SELECT :fqn, OBJECT_CONSTRUCT(*), NULL FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));
    EXCEPTION WHEN OTHER THEN
      INSERT INTO _DESC SELECT :fqn, NULL, :SQLERRM;
      errs := errs + 1;
    END;
  END FOR;

  CREATE OR REPLACE TEMPORARY TABLE _STAGE AS
    SELECT a.*, TRY_PARSE_JSON(d.D:agent_spec::STRING) AGENT_SPEC, d.D:default_version_name::STRING DEFAULT_VERSION_NAME,
           TRY_PARSE_JSON(d.D:versions::STRING) VERSIONS, TRY_PARSE_JSON(d.D:aliases::STRING) ALIASES, d.ERR DESCRIBE_ERROR,
           SHA2(CONCAT_WS('|', NVL(TO_JSON(TRY_PARSE_JSON(d.D:agent_spec::STRING)),'~'), NVL(a.OWNER,'~'),
                NVL(a.COMMENT,'~'), NVL(TO_JSON(a.PROFILE),'~'), NVL(d.D:default_version_name::STRING,'~'),
                NVL(d.D:versions::STRING,'~'), NVL(d.D:aliases::STRING,'~')), 256) CONFIG_HASH
    FROM _AGENTS a JOIN _DESC d USING (AGENT_FQN);

  -- Guardrail: if visibility collapsed (lost grants, secondary-role differences), do not
  -- tombstone agents that merely disappeared from view — log PARTIAL and keep them current.
  LET prev_n NUMBER := (SELECT COUNT(*) FROM AGENT_OBS.RAW.AGENT_CONFIG_HISTORY WHERE IS_CURRENT AND NOT IS_DROPPED);
  LET seen_n NUMBER := (SELECT COUNT(*) FROM _STAGE);
  LET allow_drop BOOLEAN := (prev_n = 0 OR seen_n >= prev_n * 0.8);
  IF (NOT allow_drop) THEN errs := errs + 1; END IF;

  -- Close current rows whose config changed (ignore transient DESCRIBE failures) or that disappeared.
  UPDATE AGENT_OBS.RAW.AGENT_CONFIG_HISTORY h SET VALID_TO = :now_ts, IS_CURRENT = FALSE
  WHERE h.IS_CURRENT AND NOT h.IS_DROPPED AND (
        (:allow_drop AND NOT EXISTS (SELECT 1 FROM _STAGE s WHERE s.AGENT_FQN = h.AGENT_FQN))
     OR EXISTS (SELECT 1 FROM _STAGE s WHERE s.AGENT_FQN = h.AGENT_FQN
                AND s.DESCRIBE_ERROR IS NULL AND s.CONFIG_HASH <> h.CONFIG_HASH));
  closed := SQLROWCOUNT;

  -- Tombstones for dropped agents.
  INSERT INTO AGENT_OBS.RAW.AGENT_CONFIG_HISTORY
  SELECT h.AGENT_FQN, h.DATABASE_NAME, h.SCHEMA_NAME, h.AGENT_NAME, h.OWNER, h.COMMENT, h.PROFILE, h.CREATED_ON,
         h.IS_SECURE, h.AGENT_SPEC, h.DEFAULT_VERSION_NAME, h.VERSIONS, h.ALIASES, h.CONFIG_HASH,
         :now_ts, NULL, TRUE, TRUE, NULL
  FROM AGENT_OBS.RAW.AGENT_CONFIG_HISTORY h
  WHERE h.VALID_TO = :now_ts AND NOT EXISTS (SELECT 1 FROM _STAGE s WHERE s.AGENT_FQN = h.AGENT_FQN);
  dropped := SQLROWCOUNT;

  -- New versions / new agents (a re-created agent after a tombstone also opens a new row).
  UPDATE AGENT_OBS.RAW.AGENT_CONFIG_HISTORY h SET VALID_TO = :now_ts, IS_CURRENT = FALSE
  WHERE h.IS_CURRENT AND h.IS_DROPPED AND EXISTS (SELECT 1 FROM _STAGE s WHERE s.AGENT_FQN = h.AGENT_FQN);

  INSERT INTO AGENT_OBS.RAW.AGENT_CONFIG_HISTORY
  SELECT s.AGENT_FQN, s.DATABASE_NAME, s.SCHEMA_NAME, s.AGENT_NAME, s.OWNER, s.COMMENT, s.PROFILE, s.CREATED_ON,
         s.IS_SECURE, s.AGENT_SPEC, s.DEFAULT_VERSION_NAME, s.VERSIONS, s.ALIASES, s.CONFIG_HASH,
         :now_ts, NULL, TRUE, FALSE, s.DESCRIBE_ERROR
  FROM _STAGE s
  WHERE NOT EXISTS (SELECT 1 FROM AGENT_OBS.RAW.AGENT_CONFIG_HISTORY h WHERE h.AGENT_FQN = s.AGENT_FQN AND h.IS_CURRENT);
  ins := SQLROWCOUNT;

  CALL AGENT_OBS.ADMIN.SP_LOG(:run_id, 'AGENT_CONFIG', :started, :ins, :closed, NULL,
       IFF(:errs > 0, 'PARTIAL', 'OK'), :errs || ' describe errors; ' || :dropped || ' dropped'
       || IFF(:allow_drop, '', '; drop detection skipped: saw ' || :seen_n || ' of ' || :prev_n || ' agents'));
  RETURN OBJECT_CONSTRUCT('step','AGENT_CONFIG','new_versions',ins,'closed',closed,'dropped',dropped,'describe_errors',errs);
EXCEPTION WHEN OTHER THEN
  CALL AGENT_OBS.ADMIN.SP_LOG(:run_id, 'AGENT_CONFIG', :started, 0, 0, NULL, 'FAILED', :SQLERRM);
  RAISE;
END;
$$;

-- 4. Daily asset snapshot (semantic views + Cortex Search services) ----
CREATE OR REPLACE PROCEDURE ADMIN.SP_LOAD_ASSETS()
RETURNS VARIANT LANGUAGE SQL EXECUTE AS CALLER AS
$$
DECLARE
  run_id STRING DEFAULT UUID_STRING();
  started TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP();
  fqn STRING; vq NUMBER; ins NUMBER DEFAULT 0;
  c CURSOR FOR SELECT ASSET_FQN FROM _SV;
BEGIN
  SHOW SEMANTIC VIEWS IN ACCOUNT;
  CREATE OR REPLACE TEMPORARY TABLE _SV AS
    SELECT '"' || REPLACE("database_name",'"','""') || '"."' || REPLACE("schema_name",'"','""') || '"."'
             || REPLACE("name",'"','""') || '"' ASSET_FQN, OBJECT_CONSTRUCT(*) D, NULL::NUMBER VQ
    FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));
  FOR r IN c DO
    fqn := r.ASSET_FQN;
    BEGIN
      EXECUTE IMMEDIATE 'DESCRIBE SEMANTIC VIEW ' || fqn;
      SELECT COUNT(DISTINCT "object_name") INTO :vq FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()))
       WHERE "object_kind" ILIKE '%VERIFIED_QUERY%';
      UPDATE _SV SET VQ = :vq WHERE ASSET_FQN = :fqn;
    EXCEPTION WHEN OTHER THEN NULL;
    END;
  END FOR;

  SHOW CORTEX SEARCH SERVICES IN ACCOUNT;
  CREATE OR REPLACE TEMPORARY TABLE _CSS AS
    SELECT '"' || REPLACE("database_name",'"','""') || '"."' || REPLACE("schema_name",'"','""') || '"."'
             || REPLACE("name",'"','""') || '"' ASSET_FQN, OBJECT_CONSTRUCT(*) D
    FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

  DELETE FROM AGENT_OBS.RAW.ASSET_SNAPSHOT WHERE SNAPSHOT_DATE = CURRENT_DATE();
  INSERT INTO AGENT_OBS.RAW.ASSET_SNAPSHOT
  SELECT CURRENT_DATE(), 'SEMANTIC_VIEW', ASSET_FQN, D:database_name, D:schema_name, D:name, D:owner, D:comment,
         TRY_TO_TIMESTAMP_LTZ(D:created_on::STRING), VQ, D, CURRENT_TIMESTAMP() FROM _SV
  UNION ALL
  SELECT CURRENT_DATE(), 'CORTEX_SEARCH_SERVICE', ASSET_FQN, D:database_name, D:schema_name, D:name, D:owner, D:comment,
         TRY_TO_TIMESTAMP_LTZ(D:created_on::STRING), NULL, D, CURRENT_TIMESTAMP() FROM _CSS;
  ins := SQLROWCOUNT;

  CALL AGENT_OBS.ADMIN.SP_LOG(:run_id, 'ASSETS', :started, :ins, 0, NULL, 'OK', NULL);
  RETURN OBJECT_CONSTRUCT('step','ASSETS','rows',ins);
EXCEPTION WHEN OTHER THEN
  CALL AGENT_OBS.ADMIN.SP_LOG(:run_id, 'ASSETS', :started, 0, 0, NULL, 'FAILED', :SQLERRM);
  RAISE;
END;
$$;

-- 5. Users (merge; deleted users are retained) -------------------------
CREATE OR REPLACE PROCEDURE ADMIN.SP_LOAD_USERS()
RETURNS VARIANT LANGUAGE SQL EXECUTE AS CALLER AS
$$
DECLARE
  run_id STRING DEFAULT UUID_STRING();
  started TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP();
  ins NUMBER DEFAULT 0; upd NUMBER DEFAULT 0;
BEGIN
  MERGE INTO AGENT_OBS.RAW.USERS t USING (
    SELECT USER_ID, NAME, LOGIN_NAME, DISPLAY_NAME, EMAIL, TYPE, DEFAULT_ROLE, DISABLED, CREATED_ON, DELETED_ON,
           LAST_SUCCESS_LOGIN, OBJECT_CONSTRUCT(*) DETAILS,
           HASH(NAME, LOGIN_NAME, DISPLAY_NAME, EMAIL, TYPE, DEFAULT_ROLE, DISABLED, DELETED_ON, LAST_SUCCESS_LOGIN) ROW_HASH
    FROM SNOWFLAKE.ACCOUNT_USAGE.USERS
    QUALIFY ROW_NUMBER() OVER (PARTITION BY USER_ID ORDER BY DELETED_ON DESC NULLS FIRST, CREATED_ON DESC) = 1
  ) s ON t.USER_ID = s.USER_ID
  WHEN MATCHED AND t.ROW_HASH <> s.ROW_HASH THEN UPDATE SET
    NAME = s.NAME, LOGIN_NAME = s.LOGIN_NAME, DISPLAY_NAME = s.DISPLAY_NAME, EMAIL = s.EMAIL, TYPE = s.TYPE,
    DEFAULT_ROLE = s.DEFAULT_ROLE, DISABLED = s.DISABLED, CREATED_ON = s.CREATED_ON, DELETED_ON = s.DELETED_ON,
    LAST_SUCCESS_LOGIN = s.LAST_SUCCESS_LOGIN, DETAILS = s.DETAILS, ROW_HASH = s.ROW_HASH, _LAST_LOADED_AT = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN INSERT VALUES (s.USER_ID, s.NAME, s.LOGIN_NAME, s.DISPLAY_NAME, s.EMAIL, s.TYPE, s.DEFAULT_ROLE,
    s.DISABLED, s.CREATED_ON, s.DELETED_ON, s.LAST_SUCCESS_LOGIN, s.DETAILS, s.ROW_HASH, CURRENT_TIMESTAMP());
  SELECT "number of rows inserted", "number of rows updated" INTO :ins, :upd FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));
  CALL AGENT_OBS.ADMIN.SP_LOG(:run_id, 'USERS', :started, :ins, :upd, NULL, 'OK', NULL);
  RETURN OBJECT_CONSTRUCT('step','USERS','inserted',ins,'updated',upd);
EXCEPTION WHEN OTHER THEN
  CALL AGENT_OBS.ADMIN.SP_LOG(:run_id, 'USERS', :started, 0, 0, NULL, 'FAILED', :SQLERRM);
  RAISE;
END;
$$;

-- 6. QUERY_HISTORY for agent-generated SQL (by query_id from SQL spans)
CREATE OR REPLACE PROCEDURE ADMIN.SP_LOAD_QUERY_HISTORY()
RETURNS VARIANT LANGUAGE SQL EXECUTE AS CALLER AS
$$
DECLARE
  run_id STRING DEFAULT UUID_STRING();
  started TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP();
  wm TIMESTAMP_LTZ;
  ins NUMBER DEFAULT 0;
BEGIN
  CREATE OR REPLACE TEMPORARY TABLE _QIDS AS
    SELECT DISTINCT e.RECORD_ATTRIBUTES:"snow.ai.observability.agent.tool.sql_execution.query_id"::STRING QUERY_ID,
           MIN(e.TIMESTAMP)::TIMESTAMP_LTZ TS
    FROM AGENT_OBS.RAW.AI_OBS_EVENTS e
    WHERE e.RECORD_ATTRIBUTES:"snow.ai.observability.agent.tool.sql_execution.query_id" IS NOT NULL
      AND NOT EXISTS (SELECT 1 FROM AGENT_OBS.RAW.AGENT_QUERY_HISTORY q
                      WHERE q.QUERY_ID = e.RECORD_ATTRIBUTES:"snow.ai.observability.agent.tool.sql_execution.query_id"::STRING)
      -- full year on first load, then only the lookback (ids never in QUERY_HISTORY don't pin the window)
      AND e.TIMESTAMP >= DATEADD(day, -IFF((SELECT COUNT(*) FROM AGENT_OBS.RAW.AGENT_QUERY_HISTORY) = 0, 365,
                                      AGENT_OBS.ADMIN.CFG('QH_LOOKBACK_DAYS')::INT), CURRENT_TIMESTAMP())
    GROUP BY 1;
  SELECT DATEADD(hour, -12, MIN(TS)) INTO :wm FROM _QIDS;
  IF (wm IS NULL) THEN
    CALL AGENT_OBS.ADMIN.SP_LOG(:run_id, 'QUERY_HISTORY', :started, 0, 0, NULL, 'OK', 'nothing new');
    RETURN OBJECT_CONSTRUCT('step','QUERY_HISTORY','inserted',0);
  END IF;

  INSERT INTO AGENT_OBS.RAW.AGENT_QUERY_HISTORY
  SELECT q.QUERY_ID, q.START_TIME, q.END_TIME, q.WAREHOUSE_NAME, q.WAREHOUSE_SIZE, q.ROLE_NAME, q.USER_NAME,
         q.EXECUTION_STATUS, q.ERROR_CODE, q.ERROR_MESSAGE, q.TOTAL_ELAPSED_TIME, q.EXECUTION_TIME, q.COMPILATION_TIME,
         q.QUEUED_OVERLOAD_TIME, q.BYTES_SCANNED, q.ROWS_PRODUCED, q.PARTITIONS_SCANNED, q.PARTITIONS_TOTAL,
         q.CREDITS_USED_CLOUD_SERVICES, q.QUERY_HASH, CURRENT_TIMESTAMP()
  FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY q JOIN _QIDS i ON i.QUERY_ID = q.QUERY_ID
  WHERE q.START_TIME >= :wm
  QUALIFY ROW_NUMBER() OVER (PARTITION BY q.QUERY_ID ORDER BY q.END_TIME DESC) = 1;
  ins := SQLROWCOUNT;

  CALL AGENT_OBS.ADMIN.SP_LOG(:run_id, 'QUERY_HISTORY', :started, :ins, 0, :wm, 'OK', NULL);
  RETURN OBJECT_CONSTRUCT('step','QUERY_HISTORY','inserted',ins,'from',wm);
EXCEPTION WHEN OTHER THEN
  CALL AGENT_OBS.ADMIN.SP_LOG(:run_id, 'QUERY_HISTORY', :started, 0, 0, :wm, 'FAILED', :SQLERRM);
  RAISE;
END;
$$;
